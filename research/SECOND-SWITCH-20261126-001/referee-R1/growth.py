"""Complete rounds with waiting and release, without taking shared distinctions.

A loose distinction has a single owner. When a birth uses it, only the two
holders now meet. Thus the counts of usable loose distinctions and the sets
of meetings suffice throughout these laws, including when a loose distinction
is barred. The one exception to recording just who meets whom is at the start:
multiple shared distinctions there must still be counted as separate places.
"""
import hashlib
import re
from collections import Counter, defaultdict, deque
from functools import lru_cache
from itertools import combinations
from operator import or_
from functools import reduce

import networkx as nx


@lru_cache(maxsize=None)
def atlas_pairs(i):
    return tuple(nx.graph_atlas(i).edges())


def pattern(name):
    if name == 'stub':
        return [0], [], 0
    if name == 'source':
        stars = [[0,1,2,9,10,11], [0,1,3], [4,5,12,13,14], [6,7,15,16,17],
                 [2,3,4,6,18,19,20], [7,8,21,22], [5,8,23,24]]
        counts = Counter(d for star in stars for d in star)
        return ([sum(counts[d] == 1 for d in star) for star in stars],
                [(u,v) for u,v in combinations(range(7),2) if set(stars[u]) & set(stars[v])], 0)
    if name == 'ring':
        return [3]*5, [(u,(u+1)%5) for u in range(5)], 0
    if name == 'copier':
        return [2,2], [(0,1)], 0
    match = re.fullmatch(r'(?:n\d+:)?(tri|g\d+):(\d+)@(\d+)', name)
    if not match:
        raise ValueError(name)
    kind, loose, site = match.groups()
    pairs = [(0,1),(1,2),(0,2)] if kind == 'tri' else atlas_pairs(int(kind[1:]))
    return list(map(int, loose)), pairs, int(site)


def components(members, sets):
    """Connected classes generated by each of the supplied sets."""
    label = {u:u for u in members}

    def rep(u):
        while u != label[u]:
            label[u] = label[label[u]]
            u = label[u]
        return u

    for group in sets:
        it = iter(group)
        first = next(it, None)
        if first is not None:
            for u in it:
                label[rep(u)] = rep(first)
    return {u:rep(u) for u in members}


def met_sets(met, live):
    # Each common knot reports all its current members, including when it has
    # long since spent everything. The common knot never reports itself.
    reports = defaultdict(list)
    for u in live:
        for common in met[u]:
            reports[common].append(u)
    return {frozenset(group) for group in reports.values() if len(group) >= 2}


def roster_groups(met, live):
    sets = met_sets(met, live)
    if not sets:
        return []
    witnesses = defaultdict(list)
    pairs = set()
    for group in sets:
        for u in group:
            witnesses[u].append(group)
        pairs.update(combinations(sorted(group), 2))
    # A maximal clique entirely met by one common knot contributes only its
    # still-uncovered pairs. Cliques not met together make one group each.
    joinable = nx.Graph()
    joinable.add_edges_from(pairs)
    large = []
    for clique in nx.find_cliques(joinable):
        if len(clique) < 3:
            continue
        ids = frozenset(clique)
        if not any(ids <= witness for witness in witnesses[clique[0]]):
            large.append(tuple(sorted(ids)))
    uncovered = pairs.copy()
    for group in large:
        uncovered.difference_update(combinations(group, 2))
    return sorted(large) + sorted(uncovered)


class State:
    def __init__(self, h, met, role, law, treatment="wait"):
        self.h, self.met, self.role, self.law = h, met, role, law
        if treatment not in ("wait","retire"):
            raise ValueError(treatment)
        self.treatment = treatment
        self.born = [0]*len(h)
        self.r = 0
        self.own = ()
        self.short = set()
        self.names = [('A'+str(i)).encode() if mask == 1 else b'' for i,mask in enumerate(role)]

    def copy(self):
        other = object.__new__(State)
        other.__dict__ = self.__dict__.copy()
        for key in ('h','role','born','names'):
            setattr(other,key,getattr(self,key).copy())
        other.met = [s.copy() for s in self.met]
        return other

    def mark(self, u, sign):
        if sign == 'add':
            self.h[u] += 1
        elif sign == 'bar' and self.h[u] > 0:
            self.h[u] -= 1
        else:
            raise ValueError((u,sign))

    def step(self):
        live = [u for u,h in enumerate(self.h) if h]
        groups = roster_groups(self.met, live)
        owed = Counter(u for group in groups for u in group)
        self.short = {u for u in live if owed[u] > self.h[u]}
        births = [group for group in groups if self.short.isdisjoint(group)]
        spent = Counter(u for group in births for u in group)
        for u in live:
            if u not in self.short:
                births.extend([(u,)] * (self.h[u] - spent[u]))
                self.h[u] = 0

        waiting = self.short if self.treatment == "wait" else set()
        if self.treatment == "retire":
            for u in self.short:
                self.h[u] = 0
        first = len(self.h)
        self.r += 1
        for j, parents in enumerate(births, first):
            self.role.append(reduce(or_, (self.role[p] for p in parents)))
            self.met.append(set(parents))
            for p in parents:
                self.met[p].add(j)
        new = range(first, first+len(births))
        demand = Counter(u for group in roster_groups(self.met, [*waiting,*new]) for u in group)
        own = []
        serial = Counter()
        for j, parents in zip(new,births):
            places_from_parents = len(parents)
            floor = 3 - places_from_parents
            asked = max(demand[j], floor, 1)
            if self.law.startswith('CAP-'):
                fresh = min(asked,int(self.law[4:]))
            elif self.law == 'REC-ONE-FEWER':
                fresh = max(asked-1,floor,0)
            elif self.law == 'ONE-FEWER' or (self.law == 'JOIN-FEWER' and len(parents)>1):
                fresh = max(asked-1,floor,1)
            elif self.law in ('ORD','JOIN-FEWER'):
                fresh = asked
            else:
                raise ValueError(self.law)
            self.h.append(fresh)
            self.born.append(self.r)
            name = b''
            if self.role[j] == 1:
                parent_names = tuple(sorted(self.names[p] for p in parents))
                which = serial[parent_names]
                serial[parent_names] += 1
                name = hashlib.sha256(repr((parent_names,which)).encode()).digest()
                own.append((name,fresh,fresh+len(parents)))
            self.names.append(name)
        self.own = tuple(sorted(own))

    def distances(self):
        dist = {u:0 for u,mask in enumerate(self.role) if mask == 1}
        queue = deque(dist)
        while queue:
            u = queue.popleft()
            for v in self.met[u]:
                if v not in dist:
                    dist[v] = dist[u]+1
                    queue.append(v)
        return dist

    def partition(self):
        live = {u for u,h in enumerate(self.h) if h}
        parts = components(live,met_sets(self.met, live))
        direct = {tuple(sorted((parts[u],parts[v]))) for u in live for v in self.met[u]
                  if v in live and parts[u] != parts[v]}
        classes = components(set(parts.values()), direct)
        return parts,direct,{u:classes[p] for u,p in parts.items()}

    def links(self, inclusive=False):
        parts,direct,classes = self.partition()
        def owns(mask, side):
            return bool(mask & side) if inclusive else mask == side
        a,b = ([u for u in parts if owns(self.role[u],side)] for side in (1,2))
        if not a or not b:
            return dict.fromkeys(('part','direct','class'))
        pa,pb = {parts[u] for u in a}, {parts[u] for u in b}
        same = bool(pa & pb)
        return {'part':same,
                'direct':same or any((p in pa and q in pb) or (q in pa and p in pb) for p,q in direct),
                'class':not {classes[u] for u in a}.isdisjoint(classes[u] for u in b)}


def start(A, B, law, change=None, join='meeting', steps=3, treatment='wait'):
    h, pairs, site = pattern(A)
    hb, bpairs, far_site = pattern(B)
    role = [1]*len(h)
    met = [set() for _ in h]
    def append(loose, mask):
        h.append(loose)
        role.append(mask)
        met.append(set())
        return len(h)-1
    def meet(u,v):
        met[u].add(v)
        met[v].add(u)
    for u,v in pairs:
        meet(u,v)
    offset = len(h)
    if B != 'stub':
        for loose in hb:
            append(loose,2)
        for u,v in bpairs:
            meet(u+offset,v+offset)
    links = []
    for i in range(steps):
        if i < steps-1:
            far = append(0,4)
            links.append(far)
        else:
            far = append(0,2) if B == 'stub' else offset+far_site
        if join == 'meeting':
            common = append(0,4)
            meet(common,site)
            meet(common,far)
            h[site] += 1
            h[far] += 1
        elif join == 'share':
            meet(site,far)
        else:
            raise ValueError(join)
        site = far
    if join == 'share':
        for u in links:
            h[u] = 1
        if B == 'stub':
            h[far] = 2
    state = State(h,met,role,law,treatment)
    if change is not None:
        action = re.fullmatch(r'(b?)(B|L)(\d+)', change)
        bar,side,index = action.groups()
        i = int(index)
        knot = (far if B == 'stub' else offset+i) if side == 'B' else links[i-1]
        state.mark(knot,'bar' if bar else 'add')
    return state
