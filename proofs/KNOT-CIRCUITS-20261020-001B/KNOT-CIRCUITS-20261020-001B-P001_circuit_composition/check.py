# ------------------------------------------------------------------ circuits

def ranges(S, n):
    return [frozenset(t[i] for t in S) for i in range(n)]


def constrained(S, Y, rg):
    return len({tuple(t[i] for i in Y) for t in S}) < prod(len(rg[i]) for i in Y)


def circuits_by_size(S, n):
    rg = ranges(S, n)
    found = []
    for size in range(2, n + 1):
        for Y in combinations(range(n), size):
            if not any(set(C) <= set(Y) for C in found) and constrained(S, Y, rg):
                found.append(Y)
    return found


def circuits_by_test(S, n):
    rg = ranges(S, n)
    return [Y for size in range(2, n + 1) for Y in combinations(range(n), size)
            if constrained(S, Y, rg) and all(not constrained(S, tuple(v for v in Y if v != w), rg) for w in Y)]


def first_failure(S, n, knots_only=False):
    rg = ranges(S, n)
    C = circuits_by_size(S, n)
    for C1, C2 in combinations(C, 2):
        if knots_only and min(len(C1), len(C2)) < 3:
            continue
        for e in sorted(set(C1) & set(C2)):
            if not constrained(S, tuple(sorted((set(C1) | set(C2)) - {e})), rg):
                return C1, C2, e
    return None


def evaluate(R, copies, n_total, visible, q=2):
    out = set()
    for a in product(range(q), repeat=n_total):
        if all(tuple(a[v] for v in c) in R for c in copies):
            out.add(tuple(a[v] for v in visible))
    return out


def join(K1, n1, K2, n2, shared):
    """K1 on variables 0..n1-1; K2 joined with its position b equal to K1's position a for (a, b) in shared."""
    pos = {b: a for a, b in shared}
    fresh = [b for b in range(n2) if b not in pos]
    for j, b in enumerate(fresh):
        pos[b] = n1 + j
    S = set()
    for t1 in K1:
        for t2 in K2:
            if all(t1[a] == t2[b] for a, b in shared):
                full = list(t1) + [None] * len(fresh)
                for b in fresh:
                    full[pos[b]] = t2[b]
                S.add(tuple(full))
    return S, n1 + len(fresh), tuple(range(n1)), tuple(sorted(pos[b] for b in range(n2)))


def hub_fails(K1, n1, K2, n2, shared, eliminated):
    S, N, C1, C2 = join(K1, n1, K2, n2, shared)
    C = circuits_by_size(S, N)
    rg = ranges(S, N)
    return C1 in C and C2 in C and not constrained(S, tuple(sorted((set(C1) | set(C2)) - {eliminated})), rg)


