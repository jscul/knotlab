"""After the run, not registered: how far the swap-made bases' additions reach (OVERLAP-READ-20261111-001).

Part 1, P4's seventeen radius-4 cases, regenerated by NAE-SURFACE's recipe as copied in the frozen census: the knots within radius 3
and 4 of the first added set, and the smallest of three greedy forcing sets.
Part 2 (after the referee found the frozen radius rule understated it): for every unfaithful swap-made base and every added set, the
least radius whose ball of knots forces it, and whether that ball is already the whole base; a base is global when no added set is
forced by a proper ball. Writes global_obstructions.json beside this file.
"""
import json, os, random, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "experiments", "OVERLAP-READ-20261111-001A", "OVERLAP-READ-20261111-001A-E001_emergence_census"))
import census as c  # noqa: E402
c.OUT = os.path.join(ROOT, "research", "OVERLAP-READ-20261111-001", "supplement_scratch")
os.makedirs(c.OUT, exist_ok=True)
d = json.load(open(os.path.join(ROOT, "artifacts", "OVERLAP-READ-20261111-001A", "OVERLAP-READ-20261111-001A-E001_emergence_census",
                                "census.json")))
fails = [r for r in d["C3"] if r["family"] == "NAE-SURFACE" and r.get("states") and not r["faithful"]
         and not any(x is not None and x <= 3 for x in r.get("locality radii", []))]
tori = c.ns_faithful_tori(c.NS_V)
index = {(t["V"], tuple(t["lattice"])): i for i, t in enumerate(tori)}
out = []
for f in fails:
    n = index[(f["V"], tuple(f["torus"]))]
    tor = tori[n]
    W = c.ns_swap_worlds(tor["V"], [tuple(t) for t in tor["T"]], f["swaps"], seed=c.NS_SEED + 1000 * n + 10 * f["swaps"] + f["rep"])
    V = tor["V"]
    b = c.SatBase(V, W)
    fr, ti, ex, na = b.emergent()
    b.close()
    S = (fr + ti + ex)[0]
    rng = random.Random(3)
    best = None
    for _ in range(3):
        g = c.greedy_forcing_set(V, W, S, rng)
        if best is None or len(g) < len(best):
            best = g
    rec = {"V": V, "torus": tor["lattice"], "edge_width": tor["edge_width"], "swaps": f["swaps"], "rep": f["rep"], "S": list(S),
           "knots": len(W), "radius 3 knots": len(c.ball_knots(W, S, 3)), "radius 4 knots": len(c.ball_knots(W, S, 4)),
           "forces at radius 3": c.forced(V, c.ball_knots(W, S, 3), S), "greedy forcing set": len(best),
           "its distinctions": len({v for t in best for v in t})}
    out.append(rec)
    print(rec, flush=True)


def part2(job):
    n, f = job
    tor = tori[n]
    W = c.ns_swap_worlds(tor["V"], [tuple(t) for t in tor["T"]], f["swaps"], seed=c.NS_SEED + 1000 * n + 10 * f["swaps"] + f["rep"])
    V = tor["V"]
    b = c.SatBase(V, W)
    fr, ti, ex, na = b.emergent()
    b.close()
    radii = []
    for S in fr + ti + ex:
        r_found = None
        for r in range(1, 10):
            ball = c.ball_knots(W, S, r)
            if c.forced(V, ball, S):
                r_found = (r, len(ball) == len(W))
                break
        radii.append(r_found)
    local = [r for r, whole in radii if not whole]
    return {"V": V, "torus": tor["lattice"], "swaps": f["swaps"], "rep": f["rep"], "added sets": len(radii),
            "least proper radius": min(local) if local else None, "global": not local}


if __name__ == "__main__":
    from multiprocessing import Pool
    unf = [r for r in d["C3"] if r["family"] == "NAE-SURFACE" and r.get("states") and not r["faithful"]]
    jobs = [(index[(r["V"], tuple(r["torus"]))], r) for r in unf]
    with Pool(12) as pool:
        p2 = pool.map(part2, jobs, chunksize=1)
    from collections import Counter
    summary = {"unfaithful": len(p2), "global": sum(1 for r in p2 if r["global"]),
               "global by swaps": dict(Counter(r["swaps"] for r in p2 if r["global"])),
               "unfaithful by swaps": dict(Counter(r["swaps"] for r in p2)),
               "least proper radius": dict(Counter(str(r["least proper radius"]) for r in p2 if not r["global"]))}
    print(summary, flush=True)
    json.dump({"part 1": out, "part 2 summary": summary, "part 2": p2},
              open(os.path.join(ROOT, "research", "OVERLAP-READ-20261111-001", "global_obstructions.json"), "w"), indent=1)
