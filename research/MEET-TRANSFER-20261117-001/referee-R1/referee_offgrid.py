"""MEET-TRANSFER-20261117-001, referee R1: off-grid Novelty+ comparator check.

The referee's own Novelty+ (referee_sls.c) on the study's test instances, generated by MEET-TRANSFER's
own `engine.planted` and checked independently (and, for `local`, compared knot for knot with
WHERE-NEXT's generator on the same seeds):
  local  alpha 4.0, window 10, n = 3200, seeds 3,500,000..3,500,049:
         p in {0.75, 0.8, 0.85, 0.9, 0.95} x wp in {0, 0.005, 0.01, 0.02}, plus the study's (0.8, 0.05)
  heavy  alpha 3.0, n = 3200, seeds 3,800,000..3,800,049:
         p in {0.5, 0.55, ..., 0.9} x wp in {0, 0.005, 0.01}
3 runs per instance, cap 4e8 (local) and 2e8 (heavy, the study's cap there), referee run seeds, a CPU-time guard of TLIM s per run (a stopped run is
counted at the cap, as the study counts censored runs). Statistic as the study's: per instance the
geometric mean of its runs, then the median over instances.

Usage: referee_offgrid.py run FAMILY P [P ...] [budget=B]   (one chunk; writes referee_offgrid_FAMILY_p<P...>.json)
  budget=B replaces the cap by a flip budget B per run (added after p = 0.9 at local ran for over 9 minutes): a run
  stopped there counts as B, so the statistic is a LOWER BOUND on the setting's flips; it can rule a setting out, not in.
       referee_offgrid.py summary                 (merges the chunks into referee_offgrid_summary.json)
"""
from __future__ import annotations

import glob
import importlib.util
import json
import math
import sys
import time
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import numpy as np  # noqa: E402

import referee_common as C  # noqa: E402

SEED0 = {"local": 3_500_000, "heavy": 3_800_000}
WPS = {"local": [0.0, 0.005, 0.01, 0.02], "heavy": [0.0, 0.005, 0.01]}
EXTRA = {"local": [(0.8, 0.05)], "heavy": []}
CELL = {"local": "local4.0w10|3200", "heavy": "heavy3.0w10|3200"}
N, INST, REPS, TLIM = 3200, 50, 3, 200.0
CAPS = {"local": 4 * 10**8, "heavy": 2 * 10**8}  # the study's test caps for these cells
# the study's screen (GRID and GRID_EDGE of its test_job.py, 8 tuning instances x 3 runs) and its three tested settings
SCREEN_P = (0.3, 0.4, 0.5, 0.6, 0.65, 0.7, 0.75, 0.8, 0.85, 0.9)
SCREEN_WP = (0.0, 0.005, 0.01, 0.02, 0.05)
A = C.ROOT / "artifacts/MEET-TRANSFER-20261117-001A/MEET-TRANSFER-20261117-001A-E001_meet_transfer"


BUDGET = {}


def job(a):
    fam, s, prm, rep = a
    cap = BUDGET.get("B", CAPS[fam])
    r = C.run(fam, N, s, "novelty_plus", prm, C.seed_of("MT-offgrid", fam, N, s, prm, rep), cap, tlimit=TLIM)
    return fam, s, prm, rep, r["flips"], r["solved"], r["timed_out"], r["cpu"]


def same_generator_check(fam, seeds):
    if fam != "local":
        return None
    spec = importlib.util.spec_from_file_location("wn_engine", C.EXP_WHERE_NEXT / "engine.py")
    wn = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(wn)
    same = 0
    for s in seeds:
        a = C.instance(fam, N, s)[0]
        b = wn.planted(fam, N, C.ALPHA[fam], s)
        same += int(np.array_equal(a.knots, b.knots) and np.array_equal(a.hidden, b.hidden))
    return {"seeds_compared": len(seeds), "identical": same}


def run_chunk(fam, ps):
    t0 = time.time()
    seeds = [SEED0[fam] + i for i in range(INST)]
    for s in seeds:
        C.instance(fam, N, s)  # generated by MEET-TRANSFER's planted and checked
    gen = same_generator_check(fam, seeds)
    settings = [(p, wp) for p in ps for wp in WPS[fam]] + [x for x in EXTRA[fam] if x[0] in ps]
    jobs = [(fam, s, prm, r) for prm in settings for s in seeds for r in range(REPS)]
    res = C.pool_map(job, jobs)
    out = {"family": fam, "n": N, "seeds": [seeds[0], seeds[-1]], "reps": REPS, "cap": CAPS[fam], "tlimit_s": TLIM,
           "same_generator_as_where_next": gen, "wall_s": None, "settings": {}}
    for prm in settings:
        rows = sorted((r for r in res if r[2] == prm), key=lambda r: (r[1], r[3]))
        capu = BUDGET.get("B", CAPS[fam])
        X = {s: [(r[4] if (r[5] and not r[6]) else capu) for r in rows if r[1] == s] for s in seeds}
        G = [math.exp(np.mean(np.log(X[s]))) for s in seeds]
        out["settings"][str(prm)] = {"params": list(prm), "geo_stat": float(np.median(G)),
                                     "lower_bound": "B" in BUDGET and any(not (r[5] and not r[6]) for r in rows),
                                     "budget": BUDGET.get("B"),
                                     "pooled_median": float(np.median(np.concatenate([X[s] for s in seeds]))),
                                     "unsolved": int(sum(not r[5] for r in rows)),
                                     "timed_out": int(sum(r[6] for r in rows)),
                                     "cpu_s": float(sum(r[7] for r in rows)),
                                     "flips_by_instance": {str(s): X[s] for s in seeds}}
        v = out["settings"][str(prm)]
        print(f"{fam} {prm}: geo-stat {v['geo_stat']:>11.0f} pooled {v['pooled_median']:>11.0f} "
              f"unsolved {v['unsolved']} timed out {v['timed_out']} cpu {v['cpu_s']:.0f} s", flush=True)
    out["wall_s"] = time.time() - t0
    tag = "_".join(f"{p:g}" for p in ps) + (f"_budget{BUDGET['B']:.0e}" if "B" in BUDGET else "")
    C.jdump(out, C.HERE / f"referee_offgrid_{fam}_p{tag}.json")
    print("wall", out["wall_s"], "generator check", gen)


def summary():
    S = json.loads((A / "summary.json").read_text())["cells"]
    Rt = json.loads((A / "retuned.json").read_text())
    rng = np.random.default_rng(5)
    out = {}
    for fam in ("local", "heavy"):
        files = sorted(glob.glob(str(C.HERE / f"referee_offgrid_{fam}_p*.json")))
        if not files:
            continue
        sets, gens = {}, []
        for f in files:
            d = json.loads(Path(f).read_text())
            sets.update(d["settings"])
            gens.append(d["same_generator_as_where_next"])
        cell = S[CELL[fam]]
        study = {tuple(prm): cell["arms"][name]["median"] for name, algo, prm in Rt[CELL[fam]] if algo == "novelty_plus"}
        best_name = cell["best_rule"]
        best_prm = next(tuple(prm) for name, algo, prm in Rt[CELL[fam]] if name == best_name)
        study_best = cell["arms"][best_name]["median"]
        D_fig = cell["R"]["D"]["point"] * study_best
        seeds = sorted(int(s) for s in next(iter(sets.values()))["flips_by_instance"])
        G = {k: np.array([math.exp(np.mean(np.log(v["flips_by_instance"][str(s)]))) for s in seeds])
             for k, v in sets.items()}
        idx = rng.integers(0, len(seeds), (10000, len(seeds)))
        ref_key = str(best_prm)
        rows = []
        for k, v in sets.items():
            pr = tuple(v["params"])
            status = ("tested by the study" if pr in study else
                      "screened by the study, not tested" if (pr[0] in SCREEN_P and pr[1] in SCREEN_WP) else "off-grid")
            row = {"params": v["params"], "status": status, "on_study_grid": status != "off-grid",
                   "geo_stat": v["geo_stat"], "pooled_median": v["pooled_median"], "unsolved": v["unsolved"],
                   "timed_out": v["timed_out"], "over_study_best": v["geo_stat"] / study_best,
                   "lower_bound": bool(v.get("lower_bound")), "budget": v.get("budget")}
            if ref_key in G:
                rb = np.median(G[k][idx], axis=1) / np.median(G[ref_key][idx], axis=1)
                row["over_referee_run_of_study_best"] = {"point": float(np.median(G[k]) / np.median(G[ref_key])),
                                                         "ci95": [float(np.quantile(rb, .025)), float(np.quantile(rb, .975))]}
            if tuple(v["params"]) in study:
                row["study_value"] = study[tuple(v["params"])]
            rows.append(row)
        rows.sort(key=lambda r: r["geo_stat"])
        off = [r for r in rows if r["status"] != "tested by the study"]  # any setting the study did not test
        best_any, best_off = rows[0], (off[0] if off else None)
        fam_out = {"cell": CELL[fam], "study_best": {"params": list(best_prm), "median": study_best},
                   "study_novelty_plus": {str(k): v for k, v in study.items()},
                   "study_D_figure": D_fig, "study_R_D": cell["R"]["D"]["point"],
                   "generator_checks": gens, "best_any": best_any, "best_untested": best_off,
                   "R_D_against_referee_best_any": D_fig / best_any["geo_stat"],
                   "R_D_against_referee_best_untested": (D_fig / best_off["geo_stat"]) if best_off else None,
                   "rows": rows}
        out[fam] = fam_out
        print(f"== {fam}: study best {best_prm} {study_best:.0f}; D figure {D_fig:.0f} (R {cell['R']['D']['point']:.3f})")
        for r in rows:
            extra = r.get("over_referee_run_of_study_best", {})
            print(f"   {str(r['params']):14s} {r['status'][:20]:20s} geo {r['geo_stat']:>10.0f} "
                  f"/study best {r['over_study_best']:.3f} /ref run of study best "
                  f"{extra.get('point', float('nan')):.3f} {extra.get('ci95', '')} "
                  f"study {r.get('study_value', '')} cens {r['unsolved']}+{r['timed_out']}"
                  f"{' LOWER BOUND (budget %.0e)' % r['budget'] if r['lower_bound'] else ''}")
        print(f"   R_D vs referee best (any) {fam_out['R_D_against_referee_best_any']:.3f}; "
              f"vs best untested {fam_out['R_D_against_referee_best_untested']}")
    C.jdump(out, C.HERE / "referee_offgrid_summary.json")


if __name__ == "__main__":
    if sys.argv[1] == "run":
        args = [a for a in sys.argv[3:] if not a.startswith("budget=")]
        for a in sys.argv[3:]:
            if a.startswith("budget="):
                BUDGET["B"] = int(float(a[7:]))
        run_chunk(sys.argv[2], [float(x) for x in args])
    else:
        summary()
