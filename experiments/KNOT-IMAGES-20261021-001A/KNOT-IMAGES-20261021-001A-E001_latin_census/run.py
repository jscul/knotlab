def budget(law):
    m = max(law["sorts"])
    if m <= 3:
        return 2000, 8
    if m <= 5:
        return 1500, 8
    if m <= 7:
        return 600, 7
    return 300, 6


def gadgets(law):
    """Fixed systems for 3-nets, as (variable sorts, constraints)."""
    if law["family"] != "3-net":
        return []
    X, Y, Z = 0, 1, 2
    return [
        ("shared diagonal", [X, X, Y, Y, Z, Z, Z], [(0, (1, 3, 6)), (0, (0, 2, 6)), (0, (1, 2, 4)), (0, (0, 3, 5))]),
        ("two diagonals", [X, X, Y, Y, Z, Z], [(0, (0, 2, 4)), (0, (1, 3, 4)), (0, (0, 3, 5)), (0, (1, 2, 5))]),
        ("three-cycle", [X, X, Y, Y, Y, Z, Z, Z], [(0, (0, 2, 5)), (0, (1, 3, 5)), (0, (0, 3, 6)), (0, (1, 4, 6)),
                                                    (0, (0, 4, 7)), (0, (1, 2, 7))]),
        ("4-cycle", [X, X, Y, Y, Z, Z, Z, Z], [(0, (0, 2, 4)), (0, (0, 3, 5)), (0, (1, 2, 6)), (0, (1, 3, 7))]),
    ]


# ------------------------------------------------------------------ systems

def random_system(rng, law, nmax):
    sorts, cons = [], []
    for _ in range(rng.randint(1, 6)):
        ri = rng.randrange(len(law["rels"]))
        sig = law["rels"][ri][0]
        vs = []
        for s in sig:
            have = [v for v in range(len(sorts)) if sorts[v] == s]
            if not have or (len(sorts) < nmax and rng.random() < 0.45):
                sorts.append(s)
                vs.append(len(sorts) - 1)
            else:
                vs.append(rng.choice(have))
        cons.append((ri, tuple(vs)))
    return sorts, cons


def solve(law, sorts, cons):
    n = len(sorts)
    order = []
    for _, vs in cons:
        for v in vs:
            if v not in order:
                order.append(v)
    order += [v for v in range(n) if v not in order]
    pos = {v: i for i, v in enumerate(order)}
    rsets = [set(R) for _, R in law["rels"]]
    by_last = {}
    for ri, vs in cons:
        by_last.setdefault(max(pos[v] for v in vs), []).append((rsets[ri], vs))
    out, a = [], [0] * n

    def go(i):
        if i == n:
            out.append(tuple(a))
            return
        v = order[i]
        for x in range(law["sorts"][sorts[v]]):
            a[v] = x
            if all(tuple(a[u] for u in vs) in R for R, vs in by_last.get(i, ())):
                go(i + 1)
    go(0)
    return out


def free_sets(S, n, sizes=None):
    ranges = [frozenset(s[i] for s in S) for i in range(n)]
    sz = sizes or [len(r) for r in ranges]
    fr = {}
    for k in range(1, n + 1):
        for Y in combinations(range(n), k):
            need = 1
            for v in Y:
                need *= sz[v]
            fr[Y] = len({tuple(s[v] for v in Y) for s in S}) == need
    return fr, ranges


def circuits(fr):
    return [Y for Y, f in fr.items() if len(Y) > 1 and not f and all(fr[tuple(x for x in Y if x != w)] for w in Y)]


def elimination_failure(fr, cs):
    for a, b in combinations(cs, 2):
        for e in set(a) & set(b):
            if fr[tuple(sorted((set(a) | set(b)) - {e}))]:
                return [list(a), list(b), e]
    return None


def fibres(S, C, e):
    out = {}
    for s in S:
        out.setdefault(tuple(s[v] for v in C if v != e), set()).add(s[e])
    return list(out.values())


# ------------------------------------------------------------------ equivalences

def closure(B, pairs):
    parent = {x: x for x in B}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    for x, y in pairs:
        rx, ry = find(x), find(y)
        if rx != ry:
            parent[ry] = rx
    blocks = {}
    for x in B:
        blocks.setdefault(find(x), set()).add(x)
    return sorted(sorted(b) for b in blocks.values())


def partitions(items):
    if not items:
        yield []
        return
    first, rest = items[0], items[1:]
    for p in partitions(rest):
        for i in range(len(p)):
            yield p[:i] + [[first] + p[i]] + p[i + 1:]
        yield [[first]] + p


def coarser(blocks):
    out = []
    for p in partitions(list(range(len(blocks)))):
        if 1 < len(p) < len(blocks):
            out.append([sorted(x for i in part for x in blocks[i]) for part in p])
    return out


# ------------------------------------------------------------------ ternary polymorphisms, one table per sort

class Solver:
    """Ternary polymorphisms of a multi-sorted law: an operation table on each sort, found by generalized arc
    consistency and backtracking. Triples mixing sorts never meet a relation, so they carry no condition."""

    def __init__(self, law):
        self.sizes = law["sorts"]
        self.rels = [(tuple(sig), [tuple(t) for t in R]) for sig, R in law["rels"]]
        self.args = [(st, a) for st in range(len(self.sizes)) for a in product(range(self.sizes[st]), repeat=3)]
        self.idx = {k: i for i, k in enumerate(self.args)}
        self.dom0 = [set(range(self.sizes[st])) for st, _ in self.args]
        self.cons, self.by_var, seen = [], {}, set()
        for ri, (sig, R) in enumerate(self.rels):
            for ts in product(R, repeat=3):
                sc = (ri, tuple(self.idx[(sig[i], tuple(t[i] for t in ts))] for i in range(len(sig))))
                if sc not in seen:
                    seen.add(sc)
                    self.cons.append(sc)
        for ci, (_, sc) in enumerate(self.cons):
            for v in set(sc):
                self.by_var.setdefault(v, []).append(ci)

    def restrict(self, key, values):
        self.dom0[self.idx[key]] &= set(values)

    def _revise(self, dom, ci):
        ri, sc = self.cons[ci]
        support = {v: set() for v in set(sc)}
        for t in self.rels[ri][1]:
            seen, good = {}, True
            for v, x in zip(sc, t):
                if x not in dom[v] or seen.get(v, x) != x:
                    good = False
                    break
                seen[v] = x
            if good:
                for v, x in seen.items():
                    support[v].add(x)
        changed = []
        for v, s in support.items():
            if s != dom[v]:
                if not s:
                    return None
                dom[v] = s
                changed.append(v)
        return changed

    def _propagate(self, dom, queue):
        queue, inq = list(queue), set(queue)
        while queue:
            ci = queue.pop()
            inq.discard(ci)
            ch = self._revise(dom, ci)
            if ch is None:
                return False
            for v in ch:
                for cj in self.by_var.get(v, ()):
                    if cj not in inq:
                        inq.add(cj)
                        queue.append(cj)
        return True

    def solve(self, cap=CAP, rng=None):
        t0 = time.time()
        dom = [set(d) for d in self.dom0]
        if any(not d for d in dom) or not self._propagate(dom, range(len(self.cons))):
            return None

        def go(dom):
            if time.time() - t0 > cap:
                raise TimeoutError
            free = [v for v, d in enumerate(dom) if len(d) > 1]
            if not free:
                return dom
            v = min(free, key=lambda u: (len(dom[u]), -len(self.by_var.get(u, ()))))
            vals = sorted(dom[v])
            if rng is not None:
                rng.shuffle(vals)
            for x in vals:
                d2 = [set(s) for s in dom]
                d2[v] = {x}
                if self._propagate(d2, self.by_var.get(v, ())):
                    r = go(d2)
                    if r is not None:
                        return r
            return None
        r = go(dom)
        return None if r is None else {k: next(iter(r[i])) for k, i in self.idx.items()}


def table_out(F, sizes):
    return [[F[(st, a)] for a in product(range(sizes[st]), repeat=3)] for st in range(len(sizes))]


def breaks(F, st, blocks):
    cls = {x: i for i, b in enumerate(blocks) for x in b}
    pairs = sorted(((x, y) for b in blocks for x in b for y in b), key=lambda q: q[0] == q[1])
    for p, q, r in product(pairs, repeat=3):
        if cls[F[(st, (p[0], q[0], r[0]))]] != cls[F[(st, (p[1], q[1], r[1]))]]:
            return [list(p), list(q), list(r)]
    return None


# ------------------------------------------------------------------ one law

def census(name):
    law = LAWS[name]
    rng = random.Random(f"{SEED}-{name}")
    N, nmax = budget(law)
    row = {"law": name, "family": law["family"], "sorts": law["sorts"], "group_isotope": law.get("group_isotope"),
           "square": law.get("square"), "systems": 0, "failure": None, "collapse": None}
    kept, ranges, knot_ranges, refl, sources = [], set(), set(), {}, {}
    systems = [(g[1], g[2], g[0]) for g in gadgets(law)]
    t0 = time.time()
    i = 0
    while i < N + len(systems):
        if i < len(systems):
            sorts, cons, label = systems[i]
        else:
            sorts, cons = random_system(rng, law, nmax)
            label = "random"
        i += 1
        S = solve(law, sorts, cons)
        if not S:
            continue
        row["systems"] += 1
        n = len(sorts)
        fr, rg = free_sets(S, n)
        cs = circuits(fr)
        f = elimination_failure(fr, cs)
        if f:
            row["failure"] = {"source": label, "sorts": sorts, "constraints": [[ri, list(vs)] for ri, vs in cons],
                              "circuits_and_shared": f}
            break
        kept.append((sorts, cons))
        keyed = [(sorts[v], rg[v]) for v in range(n)]
        ranges.update(keyed)
        for u, v in combinations(range(n), 2):
            if keyed[u] == keyed[v] and len(rg[u]) > 1:
                P = {(s[u], s[v]) for s in S}
                if all((x, x) in P for x in rg[u]) and len(P) < len(rg[u]) ** 2:
                    P = frozenset(P | {(y, x) for x, y in P})
                    refl.setdefault(keyed[u], set()).update(P)
                    sources.setdefault(keyed[u], {}).setdefault(P, {"sorts": sorts, "constraints": [[ri, list(vs)] for ri, vs in cons],
                                                                     "pair": [u, v]})
        for C in cs:
            if len(C) >= 3:
                knot_ranges.update(keyed[v] for v in C)
            for e in C:
                lam = frozenset((x, y) for F in fibres(S, C, e) for x in F for y in F)
                if len(lam) < len(rg[e]) ** 2:
                    refl.setdefault(keyed[e], set()).update(lam)
                    sources.setdefault(keyed[e], {}).setdefault(lam, {"sorts": sorts, "constraints": [[ri, list(vs)] for ri, vs in cons],
                                                                       "circuit": list(C), "variable": e})
    row["seconds_sampling"] = round(time.time() - t0, 1)
    tops = {B: closure(sorted(B[1]), refl.get(B, ())) for B in ranges}
    collapsed = sorted([B[0], sorted(B[1])] for B in ranges if len(B[1]) > 1 and len(tops[B]) == 1)
    if collapsed and not row["failure"]:
        row["collapse"] = collapsed
        # witnesses: a few observed relations on the first collapsed range whose join is already total
        B = next(B for B in ranges if [B[0], sorted(B[1])] == collapsed[0])
        chosen, union = [], set()
        for rel, src in sorted(sources[B].items(), key=lambda kv: -len(kv[0])):
            if len(closure(sorted(B[1]), union | rel)) < len(closure(sorted(B[1]), union)) or not chosen:
                chosen.append(src)
                union |= rel
            if len(closure(sorted(B[1]), union)) == 1:
                break
        row["collapse_witnesses"] = {"range": [B[0], sorted(B[1])], "sources": chosen}
    if row["failure"] or row["collapse"]:
        return row
    key = lambda B: f"{B[0]}:" + ",".join(map(str, sorted(B[1])))
    row["ranges"] = sorted(key(B) for B in ranges)
    row["knot_ranges"] = sorted(key(B) for B in knot_ranges)
    row["tops"] = {key(B): tops[B] for B in ranges}

    # Mal'tsev modulo the tops on the knot ranges, one table per sort (skipped when a relation has over 80 tuples, since
    # the search then has more than half a million triples of tuples to propagate)
    t1 = time.time()
    if max(len(R) for _, R in law["rels"]) > 80:
        row.update({"maltsev_knot_ranges": "skipped (too large)", "table_knot_ranges": None, "certified": {},
                    "certificates": {}, "pool": []})
        return finish(row, law, kept, tops, {}, key, t0)
    F, row["maltsev_knot_ranges"] = None, "none"
    for exact in (True, False):
        Sv = Solver(law)
        for B in knot_ranges:
            cls = {x: b for b in tops[B] for x in b}
            for x in B[1]:
                for y in B[1]:
                    Sv.restrict((B[0], (x, y, y)), [x] if exact else cls[x])
                    Sv.restrict((B[0], (x, x, y)), [y] if exact else cls[y])
        try:
            F = Sv.solve(CAP // 2 if max(law["sorts"]) <= 7 else 4 * CAP)
        except TimeoutError:
            F, row["maltsev_knot_ranges"] = None, "timeout"
        if F:
            row["maltsev_knot_ranges"] = "found"
            row["maltsev_exact_on_knot_ranges"] = exact
            break
    row["table_knot_ranges"] = table_out(F, law["sorts"]) if F else None
    row["seconds_maltsev"] = round(time.time() - t1, 1)

    # certify the tops with a pool of polymorphisms
    pool = [F] if F else []
    tries = 0
    while len(pool) < 7 and tries < 14:
        tries += 1
        Sp = Solver(law)
        for _ in range(rng.randint(1, 6)):
            k = rng.choice(Sp.args)
            Sp.restrict(k, [rng.randrange(law["sorts"][k[0]])])
        try:
            r = Sp.solve(10 if max(law["sorts"]) <= 7 else 90, rng)
        except TimeoutError:
            r = None
        if r is not None:
            pool.append(r)
    pool = [{(st, a): G[(st, tuple(a[q[i]] for i in range(3)))] for (st, a) in G} for G in pool for q in permutations(range(3))]
    cert, witnesses = {}, {}
    for B in ranges:
        if len(B[1]) < 2:
            continue
        ok, wit = True, []
        for E in coarser(tops[B]):
            w = None
            for j, G in enumerate(pool):
                w = breaks(G, B[0], E)
                if w:
                    wit.append({"equivalence": E, "pool_index": j, "pairs": w})
                    break
            if w is None:
                ok = False
        cert[key(B)], witnesses[key(B)] = ok, wit
    row["certified"], row["certificates"] = cert, witnesses
    row["pool"] = [table_out(G, law["sorts"]) for G in pool]

    return finish(row, law, kept, tops, cert, key, t0)


def finish(row, law, kept, tops, cert, key, t0):
    """Second pass: hidden circuits, tie and knot top images."""
    cls_of = {B: {x: j for j, b in enumerate(tops[B]) for x in b} for B in tops}
    st = dict.fromkeys(["hidden", "ties", "ties_bijective", "knots", "knots_functional", "knots_overlapping",
                        "knots_neither"], 0)
    examples = {}
    for sorts, cons in kept:
        S = solve(law, sorts, cons)
        n = len(sorts)
        fr, rg = free_sets(S, n)
        keyed = [(sorts[v], rg[v]) for v in range(n)]
        T = {tuple(cls_of[keyed[v]][s[v]] for v in range(n)) for s in S}
        ntop = [len(tops[keyed[v]]) for v in range(n)]
        frT, _ = free_sets(list(T), n, ntop)
        if frT != fr:
            st["hidden"] += 1
            examples.setdefault("hidden", {"sorts": sorts, "constraints": [[ri, list(vs)] for ri, vs in cons]})
        for C in circuits(fr):
            img = {tuple(t[v] for v in C) for t in T}
            if len(C) == 2:
                if all(cert.get(key(keyed[w]), True) for w in C):
                    st["ties"] += 1
                    u, v = C
                    st["ties_bijective"] += ntop[u] == ntop[v] == len(img) == len({a for a, _ in img}) == len({b for _, b in img})
            else:
                st["knots"] += 1
                kinds = []
                for j, e in enumerate(C):
                    fib = {}
                    for t in img:
                        fib.setdefault(t[:j] + t[j + 1:], set()).add(t[j])
                    lam = {(x, y) for G in fib.values() for x in G for y in G}
                    kinds.append("functional" if all(len(G) == 1 for G in fib.values())
                                 else "overlapping" if len(lam) == ntop[e] ** 2 else "neither")
                st["knots_functional"] += all(k == "functional" for k in kinds)
                st["knots_overlapping"] += "overlapping" in kinds
                st["knots_neither"] += "neither" in kinds
                if any(k != "functional" for k in kinds):
                    examples.setdefault("knot", {"sorts": sorts, "constraints": [[ri, list(vs)] for ri, vs in cons],
                                                 "knot": list(C), "kinds": kinds})
    row.update(st)
    row.update({"kept_systems": len(kept), "examples": examples, "seconds": round(time.time() - t0, 1)})
    return row




# ------------------------------------------------------------------ main

def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    names = sorted(LAWS, key=lambda nm: -max(LAWS[nm]["sorts"]))
    with Pool(min(22, len(names))) as p:
        rows = p.map(census, names)
    by = {r["law"]: r for r in rows}
    lines = []
    for r in sorted(rows, key=lambda r: r["law"]):
        if r["failure"]:
            lines.append(f"{r['law']}: failure ({r['failure']['source']}) after {r['systems']} systems")
        elif r["collapse"]:
            lines.append(f"{r['law']}: tops collapse on {r['collapse']} after {r['systems']} systems")
        else:
            lines.append(f"{r['law']}: no failure in {r['systems']} systems; Mal'tsev on knot tops {r['maltsev_knot_ranges']}; "
                         f"hidden {r['hidden']}; ties {r['ties_bijective']}/{r['ties']}; knots functional "
                         f"{r['knots_functional']}/{r['knots']} (overlapping {r['knots_overlapping']}, neither "
                         f"{r['knots_neither']}); tops {r['tops']}; certified {r['certified']}")
    bad = lambda r: bool(r["failure"] or r["collapse"])
    nets = [r for r in rows if r["family"] == "3-net"]
    survivors = [r for r in rows if not bad(r) and r["family"] != "control"]
    pgroups = ["Z2", "Z3", "Z4", "Z2xZ2", "Z5", "Z7", "Z8", "Z2xZ4"]
    predictions = {
        "H1": all(bad(r) for r in nets if not r["group_isotope"]),
        "H2": all(not bad(by[f"3-net {g}"]) for g in pgroups) and bad(by["3-net Z6"]),
        "H2b": bad(by["3-net S3"]) and bad(by["3-net D4"]) and not bad(by["3-net Q8"]),
        "H3": all(bad(r) for r in rows if r["family"] == "overlapping"),
        "H4": all(r["knots_functional"] == r["knots"] for r in survivors),
        "H5": all(r["maltsev_knot_ranges"] == "found" for r in survivors),
        "H6": all(r["hidden"] == 0 and r["ties_bijective"] == r["ties"] for r in survivors),
    }
    g1 = by["3-net non-group 5"]
    controls = {
        "C1_parity": not bad(by["parity"]) and by["parity"]["maltsev_knot_ranges"] == "found",
        "C2_neither_knot_fails": bool(by["neither-knot"]["failure"]),
        "C3_non_group_5_fails_on_the_shared_diagonal": bool(g1["failure"]) and g1["failure"]["source"] == "shared diagonal",
        "C4_Z6_collapses": bool(by["3-net Z6"]["collapse"]) or bool(by["3-net Z6"]["failure"]),
    }
    result = {"experiment": "KNOT-IMAGES-20261021-001A-E001", "laws": len(rows),
              "survivors": sorted(r["law"] for r in rows if not bad(r)),
              "predictions": predictions, "controls": controls,
              "signal": all(predictions.values()) and all(controls.values()), "seconds": round(time.time() - t0, 1)}
    with (OUT / "raw_rows.jsonl").open("w") as f:
        for r in rows:
            f.write(json.dumps(r, sort_keys=True, default=list) + "\n")
    (OUT / "result.json").write_text(json.dumps(result, indent=1, sort_keys=True) + "\n")
    text = "\n".join(lines) + "\n" + json.dumps(result, indent=1, sort_keys=True) + "\n"
    (OUT / "run_output.txt").write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
