def span(words):
    result = {0}
    for word in words:
        if word not in result:
            result |= {old ^ word for old in result}
    return result


def rank(space):
    assert len(space) and len(space) & (len(space) - 1) == 0
    return len(space).bit_length() - 1


def cap(value, cutoff):
    return cutoff + 1 if value is None else min(value, cutoff + 1)


def pair_minima(equations, pairs, cutoff=None):
    minima = dict.fromkeys(pairs, None)
    witnesses = {}
    minimal = []
    for word in sorted(equations - {0}, key=lambda word: (word.bit_count(), word)):
        size = word.bit_count()
        if cutoff is not None and size > cutoff:
            break
        if any(word & old == old for old in minimal):
            continue
        minimal.append(word)
        for pair in combinations(bits(word), 2):
            if minima[pair] is None:
                minima[pair] = size
                witnesses[pair] = word
    return minima, witnesses


def cliques(table, width, size):
    higher = [mask(j for j in range(i + 1, width) if cap(table[i, j], size) <= size)
              for i in range(width)]

    def extend(prefix, pool, left):
        if not left:
            yield prefix
        while pool.bit_count() >= left > 0:
            bit = pool & -pool
            pool ^= bit
            yield from extend(prefix | bit, pool & higher[bit.bit_length() - 1], left - 1)

    return set(extend(0, (1 << width) - 1, size))


def force_from_table(table, width, cutoff):
    """Keep the necessary short words and repeatedly force a sole attaining bond."""
    by_size = {size: cliques(table, width, size) for size in range(3, cutoff + 1)}
    shapes = set.union(*by_size.values())
    allowed_short = shapes.copy()
    if cutoff == 6:
        allowed_short.update(a | b for a, b in combinations(by_size[3], 2) if not a & b)
    obligations = defaultdict(set)
    for word in shapes:
        for pair in combinations(bits(word), 2):
            if table[pair] == word.bit_count():
                obligations[pair].add(word)
    assert set(obligations) == {pair for pair, value in table.items() if cap(value, cutoff) <= cutoff}
    known = {0}
    rounds = []
    while True:
        proper_words = [w for w in known if 0 < w.bit_count() < cutoff]
        viable = {word for word in shapes if not any(old != word and word & old == old for old in proper_words)
                  and all(0 == (combined := word ^ old) or combined.bit_count() > cutoff
                          or combined in allowed_short for old in known)}
        forcing_pairs = []
        for pair, candidates in sorted(obligations.items()):
            possible = viable & candidates
            assert possible, (cutoff, pair, rank(known))
            if len(possible) == 1:
                word, = possible
                if word not in known:
                    forcing_pairs.append((pair, word))
        forced = {word for _, word in forcing_pairs}
        rounds.append({"rank_before": rank(known), "viable_bonds": len(viable),
                       "forces": [{"pair": pair, "support": bits(word)} for pair, word in forcing_pairs]})
        if not forced:
            return known, viable - known, allowed_short, rounds
        known = span(known | forced)


def all_compatible_spaces(table, width, known, unresolved, allowed_short):
    """Every reachable rival is generated by ≤6-bonds within the width rank bound."""
    limit = 1 + (width - 3) // 2
    residuals = {min(word ^ old for old in known) for word in unresolved} - {0}
    queue = [frozenset(known)]
    seen = set(queue)
    matches = []
    full_matches = []
    tested_ranks = Counter()
    for code in queue:
        k_values, _ = pair_minima(code, table, cutoff=6)
        r = rank(code)
        tested_ranks[r] += 1
        if all(cap(k_values[pair], 6) == cap(value, 6) for pair, value in table.items()):
            matches.append(code)
            full, _ = pair_minima(code, table)
            if full == table:
                full_matches.append(code)
        if r >= limit:
            continue
        for representative in sorted(residuals - code):
            coset = {word ^ representative for word in code}
            if any(word.bit_count() <= 6 and word not in allowed_short for word in coset):
                continue
            enlarged = frozenset(code | coset)
            if enlarged not in seen:
                seen.add(enlarged)
                queue.append(enlarged)
    return matches, full_matches, {"rank_ceiling": limit, "initial_unforced_cosets": len(residuals),
                                   "spaces_tested_by_rank": dict(sorted(tested_ranks.items()))}


def first_six_gate(width, known):
    """Enumerate every low-site prefix before a putative first six-place site."""
    low = sorted(word for word in known if 3 <= word.bit_count() <= 5)
    seed, = (word for word in low if word.bit_count() == 3)
    pool = [word for word in low if word == seed or (word & seed).bit_count() <= 1]
    queue = [frozenset((seed,))]
    seen = set(queue)
    by_size = Counter()
    triple_positive_unused = Counter()
    candidates_for_first_six = 0
    for state in queue:
        by_size[len(state)] += 1
        incidence = tuple((str(word), bits(word)) for word in sorted(state))
        holders, adjacent = literal.incidence(incidence)
        if literal.direct_triples(holders, adjacent):
            unused = width - len(holders)
            triple_positive_unused[unused] += 1
            candidates_for_first_six += unused >= 3
        for word in pool:
            if word in state:
                continue
            used = tuple(bit for bit in bits(word) if bit in holders)
            if word.bit_count() - len(used) not in (2, 3):
                continue
            if any(len(holders[bit]) != 1 for bit in used):
                continue
            parents = tuple(holders[bit][0] for bit in used)
            if not literal.legal(parents, adjacent):
                continue
            next_state = state | {word}
            if next_state not in seen:
                seen.add(next_state)
                queue.append(next_state)
    return {"unique_ternary_seed": bits(seed), "candidate_low_site_supports": [bits(word) for word in pool],
            "excluded_by_seed_overlap": [bits(word) for word in low if word not in pool],
            "reachable_low_prefixes": len(seen), "prefix_counts_by_sites": dict(sorted(by_size.items())),
            "triple_positive_prefixes_by_unused_distinctions": dict(sorted(triple_positive_unused.items())),
            "prefixes_allowing_a_first_six_site": candidates_for_first_six,
            "all_rival_stars_forced": candidates_for_first_six == 0 and len(pool) == rank(known)}


def table_only(table, width):
    lower = {}
    known_short = {}
    for cutoff in (3, 4, 5, 6):
        forced, ambiguous, allowed, rounds = force_from_table(table, width, cutoff)
        known_short[cutoff] = forced
        lower[cutoff] = {"forced_rank": rank(forced), "unforced_short_bonds": len(ambiguous), "passes": rounds}
    matches, full, analysis = all_compatible_spaces(table, width, forced, ambiguous, allowed)
    gate = first_six_gate(width, known_short[5]) if lower[5]["unforced_short_bonds"] == 0 else None
    return known_short, matches, full, {"through_cutoff": lower, "six_cutoff_spaces": len(matches),
                                      "full_table_spaces": len(full), "five_cutoff_first_six_gate": gate, **analysis}


def altered_model(table, equations):
    assert W not in equations
    augmented = equations | {W ^ old for old in equations}
    guessed, witnesses = pair_minima(augmented, table)
    differences = [pair for pair in table if table[pair] != guessed[pair]]
    first = min(min(x for x in (table[pair], guessed[pair]) if x is not None) for pair in differences)
    discriminators = [pair for pair in differences if cap(table[pair], first) != cap(guessed[pair], first)]

    def show(pair):
        return {"pair": pair, "physical_K": table[pair], "augmented_K": guessed[pair],
                "augmented_bond": bits(witnesses[pair]) if pair in witnesses else None}

    assert all(value is not None for value in (table[pair] for pair in combinations(bits(W), 2)))
    return {"new_rank": rank(augmented), "shortest_new_equation": min((W ^ old).bit_count() for old in equations),
            "all_pairs_of_W": [show(pair) for pair in combinations(bits(W), 2)],
            "full_pair_entries_changed": len(differences), "first_distinguishing_cutoff": first,
            "first_cutoff_discriminators": [show(pair) for pair in discriminators]}


def symmetry_checks(table, width, equations, history, legal):
    result = []
    for cutoff in (3, 4, 5, 6, None):
        def value(i, j):
            if i == j:
                return 0
            original = table[tuple(sorted((i, j)))]
            return original if cutoff is None else cap(original, cutoff)

        matrix = tuple(tuple(value(i, j) for j in range(width)) for i in range(width))
        order, _, generators = isometries.Quotient.make(matrix).automorphisms()
        permission_failure = code_failure = None
        for mapping in generators:
            assert not isometries.disagreement(matrix, matrix, mapping)
            if permission_failure is None:
                for triple in legal:
                    image = tuple(sorted(mapping[i] for i in triple))
                    if image not in legal:
                        permission_failure = {"legal": triple, "forbidden": image, "permutation": mapping}
                        break
            if code_failure is None:
                for site, check in history:
                    image = tuple(sorted(mapping[i] for i in check))
                    if mask(image) not in equations:
                        code_failure = {"site": site, "non_equation_image": image, "permutation": mapping}
                        break
        result.append({"cutoff": cutoff, "group_order": order, "generators_checked": len(generators),
                       "opposing_triple": permission_failure, "changed_code_only_or_with_verdict": code_failure})
    return result


def attach(history, name, parents, h):
    holders, adjacency = literal.incidence(history)
    assert literal.legal(parents, adjacency)
    used = tuple(min(bit for bit, sites in holders.items() if sites == [parent]) for parent in parents)
    return (*history, (name, (*used, *range(len(holders), len(holders) + h))))


def first_step_control():
    holders, adjacency = literal.incidence(CORE)
    loose = sorted(bit for bit, sites in holders.items() if len(sites) == 1)
    counts, positives = Counter(), Counter()
    for size in (1, 2, 3):
        for inputs in combinations(loose, size):
            if not literal.legal(tuple(holders[bit][0] for bit in inputs), adjacency):
                continue
            for h in (2, 3):
                history = (*CORE, ("u", (*inputs, *range(len(holders), len(holders) + h))))
                literal.replay(history)
                counts[size] += 1
                positives[size] += bool(literal.direct_triples(*literal.incidence(history)))
    return {"legal_extensions_by_parent_count": dict(counts), "triple_positive": dict(positives)}


def shorter_translation(table, forced):
    t, q = (mask(dict(CORE)[site]) for site in ("t", "q"))
    assert {t, q} <= forced
    translated = W ^ t ^ q
    assert bits(translated) == (0, 7, 11, 12)
    assert table[7, 12] > 4
    return {"two_words_forced_by_K4": (bits(t), bits(q)), "translated_word": bits(translated),
            "pair": (7, 12), "physical_K": table[7, 12], "hypothetical_upper_bound_K": 4}


def sharp_physical_swap(history, table, equations, width, legal, mark):
    permutation = list(range(width))
    for a, b in ((5, 8), (10, 13)):
        permutation[a], permutation[b] = b, a

    def image(group):
        return tuple(sorted(permutation[i] for i in group))

    p, w = (mask(dict(CORE)[site]) for site in ("p", "w"))
    assert mask(image(bits(W))) == p ^ w
    assert p ^ w in equations
    renamed = tuple((site, image(group)) for site, group in history)
    physical, code, _, _, cuts = literal.measure(renamed, width)
    renamed_table = {pair: minimum[0] for pair, minimum in cuts.items()}
    assert W in code and W not in equations and rank(code) == rank(equations)
    assert all(renamed_table[image(pair)] == value for pair, value in table.items())
    assert all(cap(renamed_table[pair], 3) == cap(value, 3) for pair, value in table.items())
    assert table[0, 5] == 4 < renamed_table[0, 5]
    verdict = None
    if mark is not None:
        forbidden = image(mark)
        assert mark in legal and forbidden not in legal
        assert forbidden in physical["exact_legal_triples"] and mark not in physical["exact_legal_triples"]
        assert forbidden[0] == 5 and literal.incidence(history)[0][5] == ["t", "c"]
        verdict = {"original_legal": mark, "transported_forbidden_on_original": forbidden,
                   "original_marks_forbidden_on_renamed_rival": mark}
    return {"permutation": permutation, "all_K3_pairs_checked": len(table), "W_in_renamed_actual_code": True,
            "image_of_W_is_adjacent_stars_sum": bits(p ^ w), "opposing_real_verdict": verdict,
            "K4_mismatch": {"pair": (0, 5), "original_K": table[0, 5], "renamed_K": renamed_table[0, 5]},
            "renamed_literal_history": physical["history"], "renamed_legal_triples": physical["exact_legal_triples"]}


def analyze(name, history, target=None):
    width = len(literal.incidence(history)[0])
    physical, equations, events, holders, measured = literal.measure(history, width)
    table = {pair: record[0] for pair, record in measured.items()}
    sources, compatible, full, certificate = table_only(table, width)
    assert all(forced <= equations for forced in sources.values()) and equations in compatible and equations in full
    gate = certificate["five_cutoff_first_six_gate"]
    assert gate is not None and gate["all_rival_stars_forced"] and sources[5] == equations
    assert {tuple(sorted(row)) for _, row in history} == set(gate["candidate_low_site_supports"])
    redacted = {pair: value if value <= 5 else None for pair, value in table.items()}
    redacted_known, redacted_ambiguous, _, _ = force_from_table(redacted, width, 5)
    assert not redacted_ambiguous and redacted_known == sources[5]
    assert first_six_gate(width, redacted_known) == gate
    certificate["all_entries_above_K5_erased_in_repeat_check"] = True
    legal = set(physical["exact_legal_triples"])
    observed = symmetry_checks(table, width, equations, history, sorted(legal))
    if target is not None:
        assert target in legal
        _, adjacency = literal.incidence(history)
        parents = tuple(holders[bit][0] for bit in target)
        target_record = {"mark": target, "holders": parents, "pair_witnesses": [sorted(adjacency[a] & adjacency[b])
                                                                              for a, b in combinations(parents, 2)]}
    else:
        target_record = None

    mapping = list(range(width))
    Random(82 + width).shuffle(mapping)

    def image(group):
        return tuple(sorted(mapping[i] for i in group))

    renamed = tuple((site, image(support)) for site, support in history)
    ren, r_equations, _, _, r_measured = literal.measure(renamed, width)
    r_table = {pair: record[0] for pair, record in r_measured.items()}
    assert all(r_table[image(pair)] == value for pair, value in table.items())
    assert {image(triple) for triple in legal} == set(ren["exact_legal_triples"])
    r_sources, r_compatible, r_full, renaming_certificate = table_only(r_table, width)

    def spaces_image(spaces):
        return {frozenset(mask(image(bits(word))) for word in space) for space in spaces}

    for k, original in sources.items():
        assert spaces_image([original]) == {frozenset(r_sources[k])}
    assert spaces_image(compatible) == set(r_compatible) and spaces_image(full) == set(r_full)
    assert spaces_image([equations]) == {frozenset(r_equations)}
    rg = renaming_certificate["five_cutoff_first_six_gate"]
    assert rg["all_rival_stars_forced"] and rg["prefix_counts_by_sites"] == gate["prefix_counts_by_sites"]
    assert {image(group) for group in gate["candidate_low_site_supports"]} == set(rg["candidate_low_site_supports"])

    extra = altered_model(table, equations)
    if name in ("base", "live_3_3_mirrored"):
        extra["two_forced_word_discriminator"] = shorter_translation(table, sources[4])
        exact_physical_control = sharp_physical_swap(history, table, equations, width, legal, target)
    else:
        exact_physical_control = None
    if name == "base":
        p = mask(events["p"]["support"])
        assert p in sources[4] and W not in equations and max(pair["physical_K"] for pair in extra["all_pairs_of_W"]) == 6
        translated = W ^ p
        assert translated.bit_count() == 6 and table[8, 10] > 6 and mask((8, 10)) & translated == mask((8, 10))
        extra["one_forced_word_discriminator"] = {"forced_by_K4": bits(p), "translated_word": bits(translated),
                                                  "pair": (8, 10), "physical_K": table[8, 10],
                                                  "hypothetical_upper_bound_K": 6}
    cutoff_four = next(record for record in observed if record["cutoff"] == 4)
    return {"case": name, "width": width, "physical": physical, "marked_core_triple": target_record,
            "table_only_certificate": certificate, "renaming": mapping, "self_isometries": observed,
            "smallest_all_rival_triple_cutoff": (5 if target is not None and cutoff_four["opposing_triple"] else None),
            "adjoining_W_abstractly": extra, "reachable_K3_control": exact_physical_control}


def main():
    cases = [analyze("base", CORE)]
    for first, last in product((2, 3), repeat=2):
        history = attach(attach(CORE, "u", ("p", "c"), first), "v", ("u", "b"), last)
        cases.append(analyze(f"live_{first}_{last}", history, (11, 18, 20 + first)))
    mirrored = attach(attach(CORE, "r", ("q", "c"), 3), "y", ("r", "b"), 3)
    cases.append(analyze("live_3_3_mirrored", mirrored, (8, 18, 23)))
    print(json.dumps({"false_support": bits(W), "all_one_step_extensions": first_step_control(),
                      "cases": cases}, indent=2))


if __name__ == "__main__":
    main()
