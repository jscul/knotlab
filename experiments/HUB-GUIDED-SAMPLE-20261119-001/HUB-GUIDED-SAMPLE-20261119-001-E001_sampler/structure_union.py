"""Count distinct unions of missing-neighbor sets across two projecting blocks.

A canonical reduced Boolean decision diagram supports integer counts and uniform
ranked sampling. Exhaustive small contexts check the calculation directly.
"""
import argparse
import hashlib
import json
import random
from pathlib import Path
from time import monotonic


def bits(value):
    while value:
        low = value & -value
        yield low.bit_length() - 1
        value -= low


def read_blocks(path):
    blocks = [list(map(int, line.split())) for line in path.read_text().splitlines()]
    n, number = blocks.pop(0)
    assert len(blocks) == number
    return n, blocks


def context(blocks, left_id, right_id):
    left_block, right_block = set(blocks[left_id]), set(blocks[right_id])
    left, right = sorted(left_block - right_block), sorted(right_block - left_block)
    position = {x: i for i, x in enumerate(left)}
    common = dict.fromkeys(right, 0)
    for block in blocks:
        mask = sum(1 << position[x] for x in block if x in position)
        if mask:
            for x in block:
                if x in common:
                    common[x] |= mask
    all_left = (1 << len(left)) - 1
    return left, right, {v: all_left ^ m for v, m in common.items()}


def irreducible(rows):
    """Keep one name for each mask not generated by unions of smaller masks."""
    kept = []
    seen = set()
    for name, mask in sorted(rows.items(), key=lambda pair: (pair[1].bit_count(), pair[0])):
        if not mask or mask in seen:
            continue
        seen.add(mask)
        covered = 0
        for _, small in kept:
            if small & mask == small:
                covered |= small
                if covered == mask:
                    break
        if covered != mask:
            kept.append((name, mask))
    return dict(kept)


def transposed(rows, column_names):
    out = [0] * len(column_names)
    for i, row in enumerate(rows.values()):
        for j in bits(row):
            out[j] |= 1 << i
    return dict(zip(column_names, out))


def minimum_rows_by_column(rows, number):
    result = [[] for _ in range(number)]
    for row in sorted(set(rows), key=lambda x: (x.bit_count(), x)):
        for j in bits(row):
            if not any(old & row == old for old in result[j]):
                result[j].append(row)
    return result


def project(relation, names, columns=None):
    dimensions = irreducible(relation if columns is None else {j: relation[j] for j in columns})
    generators = irreducible(transposed(dimensions, names))
    return list(dimensions), list(generators), list(generators.values())


class Limit(Exception):
    pass


class Diagram:
    def __init__(self, variables, limit):
        self.n = variables
        self.limit = limit
        self.nodes = [(variables, 0, 0), (variables, 1, 1)]
        self.unique = {}
        self.memo = {}
        self.count_memo = {0: 0, 1: 1}

    def node(self, var, off, on):
        if off == on:
            return off
        key = var, off, on
        if key not in self.unique:
            if len(self.nodes) >= self.limit:
                raise Limit
            self.unique[key] = len(self.nodes)
            self.nodes.append(key)
        return self.unique[key]

    def apply(self, conjunction, a, b):
        if a > b:
            a, b = b, a
        if a == 0:
            return 0 if conjunction else b
        if a == 1:
            return b if conjunction else 1
        if a == b:
            return a
        key = conjunction, a, b
        if key in self.memo:
            return self.memo[key]
        va, a0, a1 = self.nodes[a]
        vb, b0, b1 = self.nodes[b]
        var = min(va, vb)
        if va != var:
            a0 = a1 = a
        if vb != var:
            b0 = b1 = b
        off = self.apply(conjunction, a0, b0)
        on = self.apply(conjunction, a1, b1)
        answer = self.node(var, off, on)
        self.memo[key] = answer
        return answer

    def combine(self, conjunction, nodes):
        nodes = sorted(set(nodes))
        if not nodes:
            return int(conjunction)
        while len(nodes) > 1:
            pair = [self.apply(conjunction, nodes[i], nodes[i+1])
                    for i in range(0, len(nodes)-1, 2)]
            if len(nodes) % 2:
                pair.append(nodes[-1])
            nodes = pair
        return nodes[0]

    def models(self, root, start=0):
        pos, a, b = self.nodes[root]
        if root not in self.count_memo:
            self.count_memo[root] = self.models(a, pos+1) + self.models(b, pos+1)
        return self.count_memo[root] << (pos-start)

    def unrank(self, root, rank):
        assert 0 <= rank < self.models(root)
        mask = 0
        for i in range(self.n):
            pos, a, b = self.nodes[root]
            if pos > i:
                a = b = root
            low_count = self.models(a, i+1)
            if rank < low_count:
                root = a
            else:
                root = b
                rank -= low_count
                mask |= 1 << i
        assert root == 1 and rank == 0
        return mask


def variable_order(scopes, n):
    """Greedy min-fill approximation using the current degree as tie breaker."""
    adj = [0] * n
    for union in scopes:
        for k in bits(union):
            adj[k] |= union ^ (1 << k)
    active = (1 << n) - 1
    result = []
    while active:
        def score(i):
            nei = active & adj[i]
            return (sum((nei & ~adj[j]).bit_count() - 1 for j in bits(nei)),
                    nei.bit_count(), i)
        i = min(bits(active), key=score)
        active ^= 1 << i
        local = active & adj[i]
        for j in bits(local):
            adj[j] |= local ^ (1 << j)
        result.append(i)
    return result


def make_diagram(rows, size, limit, order_rule="reverse-fill"):
    terms = minimum_rows_by_column(rows, size)
    obligatory = []
    for j, supports in enumerate(terms):
        intersection = (1 << size) - 1
        for support in supports:
            intersection &= support
        obligatory.append(intersection if supports else 1 << j)
    def generators(mask):
        covered = 0
        for j in bits(mask):
            covered |= obligatory[j] ^ (1 << j)
        return mask & ~covered
    # Split transitive implications from the remaining local alternatives.
    families = []
    for j, supports in enumerate(terms):
        for k in bits(generators(obligatory[j] ^ (1 << j))):
            families.append((j, [1 << k]))
        residual = [generators(supp & ~obligatory[j]) for supp in supports]
        if 0 not in residual:
            families.append((j, residual))
    scopes = []
    for j, alternatives in families:
        mask = 1 << j
        for term in alternatives:
            mask |= term
        scopes.append(mask)
    order = variable_order(scopes, size)
    if order_rule == "reverse-fill":
        order.reverse()
    elif order_rule == "natural":
        order = list(range(size))
    elif order_rule != "fill":
        raise ValueError(order_rule)
    pos = {j: i for i, j in enumerate(order)}
    bdd = Diagram(size, limit)
    clauses = []
    for j, alternatives in families:
        i = pos[j]
        cubes = []
        for row in alternatives:
            product = 1
            for k in sorted((pos[k] for k in bits(row)), reverse=True):
                product = bdd.node(k, 0, product)
            cubes.append(product)
        support = bdd.combine(False, cubes)
        negative = bdd.node(i, 1, 0)
        clauses.append(bdd.apply(False, negative, support))
    root = bdd.combine(True, clauses)
    return bdd, root, order


def simple_union(rows):
    unions = {0}
    for row in rows:
        unions.update([seen | row for seen in unions])
    return unions


def control():
    for raw in range(512):
        initial = [(raw >> (3*i)) & 7 for i in range(3)]
        expected = simple_union(initial)
        physical = transposed(dict(enumerate(initial)), list(range(3)))
        cols, selected_rows, rows = project(physical, list(range(3)))
        bdd, root, order = make_diagram(rows, len(cols), 4000)
        assert bdd.models(root) == len(expected)
        recovered = set()
        for rank in range(len(expected)):
            mask = bdd.unrank(root, rank)
            allowed = 7
            for j, col in enumerate(order):
                if not mask & (1 << j):
                    allowed &= ~physical[cols[col]]
            actual = 0
            for source in bits(allowed):
                actual |= initial[source]
            recovered.add(actual)
        assert recovered == expected
    return 512


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("blocks", type=Path, nargs="?")
    parser.add_argument("--left", type=int, default=35)
    parser.add_argument("--right", type=int, default=0)
    parser.add_argument("--columns", type=int)
    parser.add_argument("--pick", type=int, default=1731)
    parser.add_argument("--literal-columns", type=Path)
    parser.add_argument("--cap", type=int, default=250000)
    parser.add_argument("--order", choices=["fill","reverse-fill","natural"], default="reverse-fill")
    parser.add_argument("--out", type=Path)
    parser.add_argument("--controls", action="store_true")
    args = parser.parse_args()
    if args.controls:
        print("contexts checked", control())
    if not args.blocks:
        return
    n, blocks = read_blocks(args.blocks)
    left, right, physical = context(blocks, args.left, args.right)
    retained = list(irreducible(physical))
    if args.literal_columns:
        retained = json.loads(args.literal_columns.read_text())
    elif args.columns and len(retained) > args.columns:
        retained = random.Random(args.pick).sample(retained, args.columns)
    cols, names, rows = project(physical, left, retained)
    start = monotonic()
    info = dict(stage_sha256=hashlib.sha256(args.blocks.read_bytes()).hexdigest(), stage_n=n,
                blocks=[args.left, args.right], exclusive_block_sizes=[len(left),len(right)],
                full_irreducible_columns=len(irreducible(physical)), selected_columns=len(retained),
                distinct_columns=len(cols), distinct_rows=len(rows), cap=args.cap, order=args.order)
    try:
        bdd, root, order = make_diagram(rows, len(cols), args.cap, args.order)
        result = bdd.models(root)
        info.update(models=result, diagram_nodes_allocated=len(bdd.nodes), success=True,
                    literal_columns=[cols[j] for j in order])
    except Limit:
        info["success"] = False
    info["wall_seconds"] = monotonic() - start
    if args.out:
        args.out.write_text(json.dumps(info, indent=2)+"\n")
    print({k:v for k,v in info.items() if k!="literal_columns"})


if __name__ == "__main__":
    main()
