#!/usr/bin/env python3
"""Checks for CONTACT-CENSUS-20261022-001A-P001. The statements are in proof.md.

A contact is a three-variable knot placed on an edge as C(h_u, x_e, h_v): joints h at the vertices (hidden), one
visible spoke x per edge (a fair bit). Its transfers are the tables M(x)[h_u][h_v]. On a square torus every edge carries
the same placed contact, oriented east and north.

Checks:
- Theorem 1 (ten classes). The 204 placements of the 34 knots give 10 classes of transfer pairs under spoke swap,
  joint-value swap and reversal, with counts 12, 24, 24, 48, 12, 12, 24, 12, 24, 12. On the 3 x 2 torus (every spoke
  pattern) all placements in a class have the same number of consistent patterns.
- Theorem 2 (vacuum). The six classes with a common vacuum are consistent for every pattern on the 3 x 2 torus and on
  50 random graphs.
- Theorem 3 (extensive). Parity is frustrated by one square face (8 of 16 patterns) and, on the 3 x 3 torus, is
  consistent for exactly 2^-(cycle rank) of all patterns; swap-or-order is frustrated by a 2 x 3 domino (8 of 128) and by
  no single face.
- Theorem 4 (patch-free). Not-all-equal and 'x or (h != h')' are consistent for every pattern on every open grid up to
  3 x 4, and on the even 4 x 4 torus.
- Theorem 5 (bipartite percolation). For 'x or (h != h')' on the 3 x 3 torus (every pattern) and on sampled 5 x 5,
  3 x 4 and 5 x 6 tori: consistency equals bipartiteness of the h != h' edges, which equals the absence of a cluster
  whose winding lattice has rank 2 or is generated by an odd class.
- Pinson's formula (cited prediction). The implementation reproduces Newman and Ziff's square-torus values
  1 - R^(e) = 0.309526275 and R^(1) = 0.169415435, sums to 1 over all topologies, and gives the predicted limits for the
  experiment's shapes.

Controls, each of which must be rejected:
- 'swap-or-order has a vacuum';
- 'not-all-equal is frustrated by a square face';
- 'consistency of x or (h != h') ignores the parity of windings' (the even 4 x 4 torus has wrapping clusters but is always consistent);
- 'the Pinson implementation sums to 1 with the cross term dropped' (a wrong formula).

    python3 -B check.py          verify result.json against a fresh run
    python3 -B check.py --write  write result.json
"""

