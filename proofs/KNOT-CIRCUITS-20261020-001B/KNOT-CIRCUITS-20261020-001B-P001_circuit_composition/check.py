def perm_group(gens, deg):
    G = {tuple(range(deg))}
    frontier = list(G)
    while frontier:
        new = []
        for g in frontier:
            for h in gens:
                x = tuple(g[h[i]] for i in range(deg))
                if x not in G:
                    G.add(x)
                    new.append(x)
        frontier = new
    return sorted(G)


def regular(elements, op):
    ix = {e: i for i, e in enumerate(elements)}
    return perm_group([tuple(ix[op(e, f)] for f in elements) for e in elements], len(elements))


