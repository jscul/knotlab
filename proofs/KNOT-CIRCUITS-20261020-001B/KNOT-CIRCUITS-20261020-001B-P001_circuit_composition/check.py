def preserves(f, R, arity):
    R = list(R)
    return all(tuple(f[tuple(t[j] for t in cols)] for j in range(len(R[0]))) in set(R)
               for cols in product(R, repeat=arity))


def preserves_fn(fn, R, arity):
    R = list(R)
    Rs = set(R)
    return all(tuple(fn(tuple(t[j] for t in cols)) for j in range(len(R[0]))) in Rs for cols in product(R, repeat=arity))


def tie_hub(R):
    """R(x, e) and R(z, e): circuits {x, e}, {z, e}; returns whether {x, z} is unconstrained."""
    S = {(x, e, z) for (x, e) in R for (z, e2) in R if e == e2}
    return first_failure(S, 3) is not None


