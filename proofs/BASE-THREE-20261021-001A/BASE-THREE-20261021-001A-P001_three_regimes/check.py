#!/usr/bin/env python3
"""Checks for BASE-THREE-20261021-001A-P001. The statements are in proof.md.

Laws are sets of relations on bits; systems conjoin copies with any variables identified and hide witnesses. A knot is
a circuit of three or more variables (K1-K3 on its projection). A knot forces variable v to value a at a state of the
other variables when that state extends only with v = a.

Checks:
- Theorem 3 (one-sided knots). Among all 34 knots on three variables and all 742 on four, exactly 'not all on' and
  'not all off' force values in one direction only.
- Lemma 1. In every three-variable knot, each excluded pattern q forces each variable v at q - v to the opposite of q_v.
- Theorem 2 (transmission). For all 34 x 34 ordered pairs of three-variable knots and all nine placements of the shared
  distinction, the pair with the shared distinction forgotten is one knot on the four others exactly when the two force
  it to opposite values, and has no circuit at all otherwise; the same on 3,000 sampled pairs involving four-variable
  knots.
- Theorem 5 (growth). For every knot on three variables that forces both values, chains of 2, 3 and 4 copies compose
  (best placement) into knots of 4, 5 and 6 variables.
- Corollary 4 and Theorem 6 (the regime map). Every law generated by one relation on at most three bits is classified
  exactly: pairwise when the relation is closed under majority, frozen when it is definable by one-signed clauses,
  implications and unit literals (and not pairwise), transmitting otherwise. Pairwise laws show no circuit of three or
  more variables on sampled systems; frozen laws show only one-signed knots of at most three variables; every
  transmitting law has an explicit witness system (a knot forcing both values or a circuit of four or more variables),
  found among single relations, two-copy compositions, cyclic three-copy gadgets and sampled systems. Eleven
  multi-relation laws are classified the same way.

Controls, each of which must be rejected:
- 'knots and extension coincide' (frozen knots never compose);
- 'two knots sharing a distinction always compose' (hubs occur);
- 'every one-sided knot is a clause on three variables' (four-variable ones exist);
- 'sampling random systems finds a witness for every transmitting law' (six need cyclic gadgets).

    python3 -B check.py          verify result.json against a fresh run
    python3 -B check.py --write  write result.json
"""

from __future__ import annotations

import json
import math
import random
import sys
from itertools import combinations, permutations, product
from pathlib import Path

HERE = Path(__file__).resolve().parent


# ------------------------------------------------------------------ relations and knots

def cube(n):
    return list(product((0, 1), repeat=n))


def from_mask(mask, n):
    pts = cube(n)
    return frozenset(pts[i] for i in range(len(pts)) if mask >> i & 1)


def is_knot(R):
    R = set(R)
    if not R:
        return False
    ar = len(next(iter(R)))
    rg = [len({t[i] for t in R}) for i in range(ar)]
    if ar < 3 or min(rg) < 2 or len(R) == math.prod(rg):
        return False
    return all(len({tuple(t[i] for i in range(ar) if i != d) for t in R}) == math.prod(rg[i] for i in range(ar) if i != d)
               for d in range(ar))


def forced_at(K, v):
    K = set(K)
    ar = len(next(iter(K)))
    others = [i for i in range(ar) if i != v]
    out = set()
    for pat in product((0, 1), repeat=ar - 1):
        vals = {t[v] for t in K if tuple(t[i] for i in others) == pat}
        if len(vals) == 1:
            out.add(next(iter(vals)))
    return out


def forced(K):
    return set().union(*(forced_at(K, v) for v in range(len(next(iter(K))))))


def majority_closed(R):
    return all(tuple(1 if a + b + c >= 2 else 0 for a, b, c in zip(x, y, z)) in R for x in R for y in R for z in R)


def ihsb(R, n, sign):
    """R is the conjunction of its implied clauses of these forms: one-signed clauses of the given sign (any width),
    implications x -> y, unit literals of either sign."""
    clauses = [[(v, sign) for v in S] for k in range(1, n + 1) for S in combinations(range(n), k)]
    clauses += [[(x, 0), (y, 1)] for x in range(n) for y in range(n) if x != y]
    clauses += [[(x, 1 - sign)] for x in range(n)]
    sat = lambda t, cl: any(t[v] == s for v, s in cl)
    implied = [cl for cl in clauses if all(sat(t, cl) for t in R)]
    return {t for t in cube(n) if all(sat(t, cl) for cl in implied)} == set(R)


# ------------------------------------------------------------------ systems

def solve(n, cons):
    order = []
    for _, vs in cons:
        for v in vs:
            if v not in order:
                order.append(v)
    order += [v for v in range(n) if v not in order]
    pos = {v: i for i, v in enumerate(order)}
    by_last = {}
    for R, vs in cons:
        by_last.setdefault(max(pos[v] for v in vs), []).append((R, vs))
    out, a = [], [0] * n

    def go(i):
        if i == n:
            out.append(tuple(a))
            return
        v = order[i]
        for x in (0, 1):
            a[v] = x
            if all(tuple(a[u] for u in vs) in R for R, vs in by_last.get(i, ())):
                go(i + 1)
    go(0)
    return out


def circuits_of(P, m):
    rg = [len({s[v] for s in P}) for v in range(m)]
    fr = {(): True}
    for k in range(1, m + 1):
        for Y in combinations(range(m), k):
            fr[Y] = len({tuple(s[v] for v in Y) for s in P}) == math.prod(rg[v] for v in Y)
    return sorted((Y for Y in fr if len(Y) > 1 and not fr[Y] and all(fr[tuple(u for u in Y if u != w)] for w in Y)),
                  key=lambda c: (len(c), c))


def system(cons, n, visible):
    S = solve(n, [(set(R), vs) for R, vs in cons])
    if not S:
        return None, []
    P = {tuple(s[v] for v in visible) for s in S}
    return P, circuits_of(P, len(visible))


def knots_in(P, cs):
    return [frozenset(tuple(t[i] for i in C) for t in P) for C in cs if len(C) >= 3]


# ------------------------------------------------------------------ witnesses for a law

def gadget_systems(rels):
    """Structured systems: each relation alone, two copies sharing one hidden variable, cyclic three-copy gadgets."""
    out = []
    for R in rels:
        ar = len(next(iter(R)))
        out.append(([(R, tuple(range(ar)))], ar, list(range(ar))))
        if ar >= 2:
            for i in range(ar):
                for j in range(ar):
                    v1 = list(range(ar - 1))
                    v1.insert(i, 2 * ar - 2)
                    v2 = list(range(ar - 1, 2 * ar - 2))
                    v2.insert(j, 2 * ar - 2)
                    out.append(([(R, tuple(v1)), (R, tuple(v2))], 2 * ar - 1, list(range(2 * ar - 2))))
        if ar == 3:
            for p in permutations(range(3)):
                # inputs at positions p[0], p[1] are hidden h1, h2, h3 = 3, 4, 5 ; outputs at p[2] are a, b, c = 0, 1, 2
                cons = []
                for (h, g, o) in ((3, 4, 0), (4, 5, 1), (5, 3, 2)):
                    vs = [None] * 3
                    vs[p[0]], vs[p[1]], vs[p[2]] = h, g, o
                    cons.append((R, tuple(vs)))
                out.append((cons, 6, [0, 1, 2]))
    return out


def random_systems(rng, rels, count, nmax=7):
    out = []
    for _ in range(count):
        n = rng.randint(3, nmax)
        cons = []
        for _ in range(rng.randint(1, 4)):
            R = rng.choice(rels)
            cons.append((R, tuple(rng.randrange(n) for _ in range(len(next(iter(R)))))))
        vis = sorted(rng.sample(range(n), rng.randint(3, n)))
        out.append((cons, n, vis))
    return out


def survey(rels, rng, samples):
    """Knots found on structured and sampled systems: their forced values, the largest circuit, and where a
    transmission witness first appears ('gadget' or 'random')."""
    found, biggest, witness = [], 0, None
    for tag, systems in (("gadget", gadget_systems(rels)), ("random", random_systems(rng, rels, samples))):
        for cons, n, vis in systems:
            P, cs = system(cons, n, vis)
            if P is None:
                continue
            for C in cs:
                biggest = max(biggest, len(C))
            for K in knots_in(P, cs):
                f = forced(K)
                found.append(frozenset(f))
                if witness is None and len(f) == 2:
                    witness = tag          # a knot forcing both values
            if witness is None and any(len(C) >= 4 for C in cs):
                witness = tag              # a circuit larger than any generator
    return found, biggest, witness


def classify(rels):
    """The predicted regime from exact relational tests."""
    if all(majority_closed(R) for R in rels):
        return "pairs"
    for sign in (0, 1):
        if all(ihsb(R, len(next(iter(R))), sign) for R in rels):
            return "frozen"
    return "transmitting"


# ------------------------------------------------------------------ run

def run():
    checks, controls, failures = {}, {}, []
    rng = random.Random("base-three-regimes")

    # Theorem 3 and Lemma 1
    knots3 = [from_mask(m, 3) for m in range(1, 1 << 8) if is_knot(from_mask(m, 3))]
    knots4 = [from_mask(m, 4) for m in range(1, 1 << 16) if is_knot(from_mask(m, 4))]
    one3 = [sorted(set(cube(3)) - set(K)) for K in knots3 if len(forced(K)) == 1]
    one4 = [sorted(set(cube(4)) - set(K)) for K in knots4 if len(forced(K)) == 1]
    lemma1 = all(forced_at(K, v) >= {1 - q[v]} and
                 len({t[v] for t in K if tuple(t[i] for i in range(3) if i != v) == tuple(q[i] for i in range(3) if i != v)}) == 1
                 for K in knots3 for q in set(cube(3)) - set(K) for v in range(3))
    checks["theorem_3_one_sided"] = {"knots_3": len(knots3), "knots_4": len(knots4), "one_sided_3": one3,
                                     "one_sided_4": one4}
    checks["lemma_1_every_excluded_pattern_forces_every_variable"] = lemma1
    if not (len(knots3) == 34 and len(knots4) == 742 and sorted(one3) == [[(0, 0, 0)], [(1, 1, 1)]]
            and sorted(one4) == [[(0, 0, 0, 0)], [(1, 1, 1, 1)]] and lemma1):
        failures.append("Theorem 3 or Lemma 1")

    # Theorem 2: transmission rule
    def pair_check(K, L, i, j):
        aK, aL = len(next(iter(K))), len(next(iter(L)))
        e = aK + aL - 2
        v1 = list(range(aK - 1))
        v1.insert(i, e)
        v2 = list(range(aK - 1, aK + aL - 2))
        v2.insert(j, e)
        P, cs = system([(K, tuple(v1)), (L, tuple(v2))], e + 1, list(range(e)))
        opposite = bool(forced_at(K, i) & {1 - b for b in forced_at(L, j)})
        composes = cs == [tuple(range(e))]
        hub = cs == []
        return composes == opposite and (composes or hub), composes
    tr = {"pairs": 0, "rule_holds": 0, "compose": 0, "hub": 0}
    for K in knots3:
        for L in knots3:
            for i in range(3):
                for j in range(3):
                    ok, comp = pair_check(K, L, i, j)
                    tr["pairs"] += 1
                    tr["rule_holds"] += ok
                    tr["compose"] += comp
                    tr["hub"] += not comp
    tr4 = {"pairs": 0, "rule_holds": 0, "compose": 0}
    for _ in range(3000):
        K = rng.choice(knots4)
        L = rng.choice(knots4 + knots3)
        ok, comp = pair_check(K, L, rng.randrange(4), rng.randrange(len(next(iter(L)))))
        tr4["pairs"] += 1
        tr4["rule_holds"] += ok
        tr4["compose"] += comp
    checks["theorem_2_transmission"] = {"three_variable_knots": tr, "sampled_with_four_variable_knots": tr4}
    if not (tr["rule_holds"] == tr["pairs"] == 10404 and tr4["rule_holds"] == tr4["pairs"] and tr["hub"] > 0):
        failures.append("Theorem 2")

    # Theorem 5: growth along chains
    def chain_size(K, k):
        best = 0
        for i, j in permutations(range(3), 2):
            cons, n, prev = [], 0, None
            for _ in range(k):
                vs = [None] * 3
                if prev is not None:
                    vs[j] = prev
                for p in range(3):
                    if vs[p] is None:
                        vs[p] = n
                        n += 1
                cons.append((K, tuple(vs)))
                prev = vs[i]
            shared = [cons[t][1][i] for t in range(k - 1)]
            P, cs = system(cons, n, [v for v in range(n) if v not in shared])
            if cs:
                best = max(best, max(len(c) for c in cs))
        return best
    growth = {}
    for K in knots3:
        if len(forced(K)) == 2:
            growth[str(sorted(set(cube(3)) - set(K)))] = [chain_size(K, k) for k in (2, 3, 4)]
    frozen_chains = {str(sorted(set(cube(3)) - set(K))): [chain_size(K, k) for k in (2, 3)]
                     for K in knots3 if len(forced(K)) == 1}
    checks["theorem_5_growth"] = {"transmitting_knots": len(growth),
                                  "chain_sizes": sorted({tuple(v) for v in growth.values()}),
                                  "frozen_knot_chains": frozen_chains}
    if not (len(growth) == 32 and all(v == [4, 5, 6] for v in growth.values())
            and all(v == [0, 0] for v in frozen_chains.values())):
        failures.append("Theorem 5")

    # Corollary 4 and Theorem 6: the regime map for every law generated by one relation on at most three bits
    laws = []
    for n in (1, 2, 3):
        for mask in range(1, 1 << (1 << n)):
            laws.append((f"{n}:{mask}", [from_mask(mask, n)]))
    regime = {"pairs": 0, "frozen": 0, "transmitting": 0}
    evidence_ok = {"pairs": 0, "frozen": 0, "transmitting": 0}
    witness_where = {"gadget": 0, "random": 0}
    random_only_misses = 0
    bad = []
    for name, rels in laws:
        pred = classify(rels)
        regime[pred] += 1
        found, biggest, witness = survey(rels, rng, 60 if pred != "transmitting" else 120)
        if pred == "pairs":
            ok = biggest <= 2 and not found
        elif pred == "frozen":
            signs = set().union(*found) if found else set()
            ok = bool(found) and all(len(f) == 1 for f in found) and len(signs) == 1 and biggest <= 3
        else:
            ok = witness is not None
            if witness:
                witness_where[witness] += 1
        evidence_ok[pred] += ok
        if not ok:
            bad.append((name, pred, biggest, sorted(map(sorted, found))[:4]))
    # how many transmitting laws random sampling alone (no gadgets) fails to witness
    for name, rels in laws:
        if classify(rels) != "transmitting":
            continue
        r2 = random.Random("random-only-" + name)
        hit = False
        for cons, n, vis in random_systems(r2, rels, 120):
            P, cs = system(cons, n, vis)
            if P is None:
                continue
            if any(len(C) >= 4 for C in cs) or any(len(forced(K)) == 2 for K in knots_in(P, cs)):
                hit = True
                break
        random_only_misses += not hit
    catalog_rel = {
        "NAND3": from_mask(sum(1 << i for i, t in enumerate(cube(3)) if t != (1, 1, 1)), 3),
        "OR3": from_mask(sum(1 << i for i, t in enumerate(cube(3)) if t != (0, 0, 0)), 3),
        "NAND4": frozenset(t for t in cube(4) if t != (1, 1, 1, 1)),
        "NAND2": frozenset(t for t in cube(2) if t != (1, 1)),
        "IMP": frozenset({(0, 0), (0, 1), (1, 1)}),
        "T": frozenset({(1,)}), "F": frozenset({(0,)}),
        "HORN": frozenset(t for t in cube(3) if t != (1, 1, 0)),
        "EVEN": frozenset(t for t in cube(3) if sum(t) % 2 == 0),
    }
    catalog = {"NAND3 + IMP": ["NAND3", "IMP"], "NAND3 + T": ["NAND3", "T"], "NAND3 + F": ["NAND3", "F"],
               "NAND3 + NAND2": ["NAND3", "NAND2"], "NAND3 + NAND4": ["NAND3", "NAND4"], "OR3 + IMP": ["OR3", "IMP"],
               "NAND3 + IMP + T + F": ["NAND3", "IMP", "T", "F"],
               "NAND3 + OR3": ["NAND3", "OR3"], "NAND3 + HORN": ["NAND3", "HORN"], "OR3 + NAND2": ["OR3", "NAND2"],
               "NAND3 + EVEN": ["NAND3", "EVEN"]}
    cat = {}
    for name, parts in catalog.items():
        rels = [catalog_rel[p] for p in parts]
        pred = classify(rels)
        found, biggest, witness = survey(rels, rng, 150)
        if pred == "frozen":
            signs = set().union(*found) if found else set()
            ok = bool(found) and all(len(f) == 1 for f in found) and len(signs) == 1 and biggest <= max(len(next(iter(R))) for R in rels)
        elif pred == "transmitting":
            ok = witness is not None
        else:
            ok = biggest <= 2
        cat[name] = {"regime": pred, "evidence": ok, "largest_circuit": biggest}
    checks["regime_map"] = {"laws": len(laws), "regimes": regime, "evidence_holds": evidence_ok,
                            "transmission_witness_found_by": witness_where,
                            "transmitting_laws_missed_by_random_sampling_alone": random_only_misses,
                            "counterexamples": bad, "multi_relation_catalog": cat}
    if bad or not all(v["evidence"] for v in cat.values()) or evidence_ok != regime:
        failures.append("regime map")

    controls["knots_and_extension_coincide"] = {"rejected": all(v == [0, 0] for v in frozen_chains.values())}
    controls["two_knots_sharing_a_distinction_always_compose"] = {"rejected": tr["hub"] > 0}
    controls["every_one_sided_knot_has_three_variables"] = {"rejected": len(one4) == 2}
    controls["random_sampling_witnesses_every_transmitting_law"] = {"rejected": random_only_misses > 0}
    for k, v in controls.items():
        if not v["rejected"]:
            failures.append(f"control not rejected: {k}")
    return checks, controls, failures


def main() -> int:
    write = "--write" in sys.argv[1:]
    checks, controls, failures = run()
    manifest = json.loads((HERE / "manifest.json").read_text())
    result = {
        "schema_version": 3, "artifact_id": manifest["artifact_id"], "kind": "proof", "ticket": manifest["ticket"],
        "proof": manifest["proof"], "status": "passed" if not failures else "failed", "claim": manifest["claim"],
        "foundation_contract": manifest["foundation_contract"], "semantic_domains": manifest["semantic_domains"],
        "evidence_modes": manifest["evidence_modes"], "thesis_alignment": manifest["thesis_alignment"],
        "safe_conclusions": manifest["safe_to_conclude"], "checks": checks, "controls": controls, "failures": failures,
    }
    path = HERE / "result.json"
    text = json.dumps(result, indent=2, sort_keys=True, ensure_ascii=False, default=str) + "\n"
    if write:
        path.write_text(text)
    elif not path.exists() or json.loads(path.read_text()) != json.loads(text):
        print("result.json does not match a fresh run; rerun with --write after review")
        return 1
    print(f"{result['status']}: failures {failures}")
    return 0 if not failures else 1


if __name__ == "__main__":
    raise SystemExit(main())
