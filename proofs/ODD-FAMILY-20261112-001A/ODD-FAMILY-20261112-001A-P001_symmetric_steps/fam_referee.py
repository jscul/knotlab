#!/usr/bin/env python3
"""Fresh-code referee for ODD-FAMILY-20261112-001A. Does not import fam_lib or odd_lib: its own clauses, its own family generation,
another SAT solver (Glucose 4), its own window check (on 4n distinctions, not 3n).

1. Its own scan: every union of one to three cosets of every subgroup containing -1, and every doubled-step set, generated by its own
   code and taken up to a multiplier; both SAT calls; the sets that make a harmony must be the scan's, up to a multiplier; for up to
   30 other satisfiable sets per n, the flippable pair checked in plain Python.
2. Every set reported to make a harmony: compatible words exist, none has place 0 flippable (own encoding), every compatible word
   enumerated, no two one place apart, the 4n-window has no state breaking the n-repeat.
3. The counts of H u 2H at the primes 41 to 113 (1 mod 4) recounted by plain blocking, without classes, where at most 20,000."""
import itertools
import json
import math
import sys
import time
from pathlib import Path

from pysat.solvers import Glucose4

HERE = Path(__file__).resolve().parent
T0 = time.time()


def progressions(S, n):
    return {tuple(sorted(((x) % n, (x + d) % n, (x + 2 * d) % n))) for x in range(n) for d in S}


def clauses(S, n, flip0=False):
    cl = []
    for tri in progressions(S, n):
        lits = [v + 1 for v in tri]
        cl.append(lits)
        cl.append([-l for l in lits])
    if flip0:
        # a second word equal to the first except at place 0: variables n+1..2n, x'_i = x_i (i > 0), x'_0 = not x_0
        cl += [[-(i + 1), n + i + 1] for i in range(1, n)] + [[i + 1, -(n + i + 1)] for i in range(1, n)]
        cl += [[1, n + 1], [-1, -(n + 1)]]
        for tri in progressions(S, n):
            lits = [n + v + 1 for v in tri]
            cl.append(lits)
            cl.append([-l for l in lits])
    return cl


def solve(cl):
    with Glucose4(bootstrap_with=cl) as g:
        return g.get_model() if g.solve() else None


def compatible(w, S, n):
    return all(len({w[a], w[b], w[c]}) == 2 for (a, b, c) in progressions(S, n))


def enumerate_words(S, n, cap):
    out = []
    with Glucose4(bootstrap_with=clauses(S, n)) as g:
        while g.solve():
            m = g.get_model()
            w = tuple(1 if m[i] > 0 else 0 for i in range(n))
            out.append(w)
            if len(out) > cap:
                return None
            g.add_clause([-(i + 1) if w[i] else i + 1 for i in range(n)])
    return out


def window_breaks(S, n):
    W = 4 * n
    ks = set()
    for d in S:
        R = (0, d % n, (2 * d) % n)
        for c in R:
            a, b = sorted((r - c) % n for r in R if r != c)
            ks.add((a, b))
    cl = []
    for (a, b) in ks:
        for j in range(W - b):
            cl.append([j + 1, j + a + 1, j + b + 1])
            cl.append([-(j + 1), -(j + a + 1), -(j + b + 1)])
    aux = []
    for m in range(n, 3 * n):
        y = W + 1 + m
        aux.append(y)
        cl += [[-y, m + 1, m + n + 1], [-y, -(m + 1), -(m + n + 1)]]
    cl.append(aux)
    return solve(cl) is not None


def unit_list(n):
    return [u for u in range(1, n) if math.gcd(u, n) == 1]


def canon(S, n, U):
    return min(tuple(sorted((u * x) % n for x in S)) for u in U)


def groups_with_minus_one(n):
    U = unit_list(n)
    out = set()
    for u in U:
        H, x = set(), 1
        while True:
            H |= {x, n - x}
            x = (x * u) % n
            if x == 1:
                break
        out.add(frozenset(H))
    return out


def family(n):
    """every union of 1 to 3 cosets of every subgroup containing -1, and every doubled-step set, as canonical forms"""
    U = unit_list(n)
    forms = set()
    for H in groups_with_minus_one(n):
        cos = {frozenset((t * h) % n for h in H) for t in range(1, n)}
        cos = sorted(cos, key=sorted)
        if len(H) == 2:
            # unions of up to three cosets of {±1} containing a unit coset: the multiplier moves the unit to 1
            m = (n - 1) // 2
            for k in range(0, 3):
                for extra in itertools.combinations(range(2, m + 1), k):
                    forms.add(canon({1, n - 1} | {e for e in extra} | {n - e for e in extra}, n, U))
            nonunit = [c for c in cos if math.gcd(min(c), n) != 1]
            for k in range(1, 4):
                for ch in itertools.combinations(nonunit, k):
                    forms.add(canon(set().union(*ch), n, U))
        else:
            for k in range(1, 4):
                for ch in itertools.combinations(cos, k):
                    forms.add(canon(set().union(*ch), n, U))
    for t in range(1, n):
        for st in ((1, 2, t), (1, 2, t, 2 * t)):
            S = {(e * s) % n for s in st for e in (1, -1)} - {0}
            forms.add(canon(S, n, U))
    return forms


def recompute(n):
    """the referee's own scan of its own canonical family at n"""
    forms = sorted(family(n))
    made, plain_checked, unsat = [], 0, 0
    for S in forms:
        if solve(clauses(S, n)) is None:
            unsat += 1
            continue
        m2 = solve(clauses(S, n, flip0=True))
        if m2 is None:
            made.append(list(S))
        elif plain_checked < 30:
            w = tuple(1 if m2[i] > 0 else 0 for i in range(n))
            assert compatible(w, S, n) and compatible((1 - w[0],) + w[1:], S, n)
            plain_checked += 1
    return {"n": n, "canonical forms": len(forms), "unsatisfiable": unsat, "make a harmony": made, "flippable pairs checked in plain Python": plain_checked}


def main():
    from multiprocessing import Pool
    scan = json.loads((HERE / "result_scan.json").read_text())["checks"]["result"]["rows"]
    rep = {"recomputed": {}, "sets that make a harmony": [], "counts": {}}
    with Pool(16) as pool:
        own = pool.map(recompute, sorted((r["n"] for r in scan), reverse=True), chunksize=1)
    own = {o["n"]: o for o in own}
    for r in scan:
        n = r["n"]
        U = unit_list(n)
        theirs = sorted({canon(x["S"], n, U) for x in r["make a harmony"]})
        mine = sorted(tuple(S) for S in own[n]["make a harmony"])
        rep["recomputed"][str(n)] = {k: v for k, v in own[n].items() if k != "n"}
        rep["recomputed"][str(n)]["agrees with the scan (the same sets, up to a multiplier)"] = theirs == mine
        for x in r["make a harmony"]:
            S = tuple(x["S"])
            sat1 = solve(clauses(S, n)) is not None
            sat2 = solve(clauses(S, n, flip0=True)) is not None
            words = enumerate_words(S, n, 10**6)
            ham1 = None
            if words is not None:
                ws = set(words)
                ham1 = sum(1 for w in words for i in range(n) if w[:i] + (1 - w[i],) + w[i + 1:] in ws)
            rep["sets that make a harmony"].append({"n": n, "S": list(S), "compatible word": sat1, "place 0 flippable somewhere": sat2,
                                                    "words": None if words is None else len(words), "one-place pairs": ham1,
                                                    "all words compatible (plain check)": words is not None and all(compatible(w, S, n) for w in words),
                                                    "4n window breaks the repeat": window_breaks(S, n)})
        print(n, "done", round(time.time() - T0), flush=True)
    cnt = json.loads((HERE / "result_counts.json").read_text())["checks"]["result"]["rows"]
    for c in cnt:
        p = c["p"]
        if p > 113:
            continue
        words = enumerate_words(tuple(c["S"]), p, 20000)
        rep["counts"][str(p)] = {"referee words": None if words is None else len(words),
                                 "check words": c["count"]["words"] if c["count"] else None}
    rep["seconds"] = round(time.time() - T0, 1)
    v = rep["sets that make a harmony"]
    rep["passed"] = (all(x["compatible word"] and not x["place 0 flippable somewhere"] and x["one-place pairs"] == 0
                         and x["all words compatible (plain check)"] and not x["4n window breaks the repeat"] for x in v)
                     and all(o["agrees with the scan (the same sets, up to a multiplier)"] for o in rep["recomputed"].values())
                     and all(c["referee words"] == c["check words"] for c in rep["counts"].values() if c["referee words"] is not None))
    (HERE / "referee.json").write_text(json.dumps(rep, indent=1) + "\n")
    print("passed" if rep["passed"] else "FAILED", rep["seconds"])


if __name__ == "__main__":
    main()
