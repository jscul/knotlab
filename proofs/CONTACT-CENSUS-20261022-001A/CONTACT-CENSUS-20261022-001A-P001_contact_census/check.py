HERE = Path(__file__).resolve().parent

I = ((1, 0), (0, 1))
S = ((0, 1), (1, 0))
J = ((1, 1), (1, 1))
U = ((1, 1), (0, 1))
L = ((1, 0), (1, 1))
A1 = ((0, 1), (1, 1))
A2 = ((1, 1), (1, 0))
NAMES = {I: "I", S: "S", J: "J", U: "U", L: "L", A1: "A1", A2: "A2"}


# ------------------------------------------------------------------ contacts

def knots3():
    cube = list(product((0, 1), repeat=3))
    out = []
    for mask in range(1, 256):
        R = frozenset(cube[k] for k in range(8) if mask >> k & 1)
        if len(R) < 8 and all(len({t[:d] + t[d + 1:] for t in R}) == 4 for d in range(3)):
            out.append(R)
    return out


def transfers(R, a, b):
    sp = [k for k in range(3) if k not in (a, b)][0]
    Ms = []
    for x in (0, 1):
        M = [[0, 0], [0, 0]]
        for t in R:
            if t[sp] == x:
                M[t[a]][t[b]] = 1
        Ms.append(tuple(map(tuple, M)))
    return tuple(Ms)


def swap_joints(M):
    return ((M[1][1], M[1][0]), (M[0][1], M[0][0]))


def transpose(M):
    return ((M[0][0], M[1][0]), (M[0][1], M[1][1]))


def canonical(pair):
    variants = []
    for f in (lambda M: M, swap_joints):
        for g in (lambda M: M, transpose):
            variants.append(tuple(sorted(NAMES[g(f(M))] for M in pair)))
    return min(variants)


# ------------------------------------------------------------------ graphs and consistency

def consistent(nv, edges, mats):
    adj = [[] for _ in range(nv)]
    for k, (u, v) in enumerate(edges):
        adj[u].append((v, k, 0))
        adj[v].append((u, k, 1))
    val = [None] * nv

    def propagate(start, a, changed):
        val[start] = a
        changed.append(start)
        stack = [start]
        while stack:
            u = stack.pop()
            for w, k, side in adj[u]:
                M = mats[k]
                allowed = [c for c in (0, 1) if (M[val[u]][c] if side == 0 else M[c][val[u]])]
                if val[w] is None:
                    if not allowed:
                        return False
                    if len(allowed) == 1:
                        val[w] = allowed[0]
                        changed.append(w)
                        stack.append(w)
                elif val[w] not in allowed:
                    return False
        return True

    for v in range(nv):
        if val[v] is not None:
            continue
        for a in (0, 1):
            changed = []
            if propagate(v, a, changed):
                break
            for w in changed:
                val[w] = None
        else:
            return False
    return True


def torus(a, b):
    """a rows, b columns; vertical (north) edges then horizontal (east) edges, each with its lattice step."""
    idx = lambda i, j: (i % a) * b + (j % b)
    edges, steps = [], []
    for i in range(a):
        for j in range(b):
            edges.append((idx(i, j), idx(i + 1, j)))
            steps.append((0, 1))          # (dx, dy): north is +y
    for i in range(a):
        for j in range(b):
            edges.append((idx(i, j), idx(i, j + 1)))
            steps.append((1, 0))
    return a * b, edges, steps


def grid(m, n):
    idx = lambda i, j: i * n + j
    edges = [(idx(i, j), idx(i, j + 1)) for i in range(m) for j in range(n - 1)]
    edges += [(idx(i, j), idx(i + 1, j)) for i in range(m - 1) for j in range(n)]
    return m * n, edges


def count_consistent(nv, edges, pair):
    return sum(consistent(nv, edges, [pair[x] for x in xs]) for xs in product((0, 1), repeat=len(edges)))


# ------------------------------------------------------------------ the h != h' subgraph: parity and windings

def bipartite_parity(nv, edges, open_mask):
    parent = list(range(nv))
    par = [0] * nv                      # parity to parent

    def find(x):
        p = 0
        root = x
        while parent[root] != root:
            p ^= par[root]
            root = parent[root]
        # path compression with parity
        y, py = x, p
        while parent[y] != y:
            nxt, pnext = parent[y], par[y]
            parent[y], par[y] = root, py
            py ^= pnext
            y = nxt
        return root, p

    for (u, v), op in zip(edges, open_mask):
        if not op:
            continue
        ru, pu = find(u)
        rv, pv = find(v)
        if ru == rv:
            if pu == pv:                 # u and v must differ but have equal parity: odd cycle
                return False
        else:
            parent[ru] = rv
            par[ru] = pu ^ pv ^ 1
    return True


def winding_classes(nv, edges, steps, open_mask, a, b):
    """Union-find with lattice displacements: for every cluster, the windings (wx, wy) of its fundamental cycles."""
    parent = list(range(nv))
    disp = [(0, 0)] * nv                 # displacement from the node to its parent, in lattice steps

    def find(x):
        dx = dy = 0
        root = x
        path = []
        while parent[root] != root:
            path.append(root)
            dx += disp[root][0]
            dy += disp[root][1]
            root = parent[root]
        # compress
        cx, cy = dx, dy
        for node in path:
            ndx, ndy = disp[node]
            parent[node] = root
            disp[node] = (cx, cy)
            cx -= ndx
            cy -= ndy
        return root, (dx, dy)

    windings = {}
    for (u, v), (sx, sy), op in zip(edges, steps, open_mask):
        if not op:
            continue
        ru, (ux, uy) = find(u)
        rv, (vx, vy) = find(v)
        # position(v) = position(u) + step; positions relative to roots
        if ru == rv:
            cx = ux + sx - vx
            cy = uy + sy - vy
            assert cx % b == 0 and cy % a == 0
            w = (cx // b, cy // a)
            if w != (0, 0):
                windings.setdefault(ru, []).append(w)
        else:
            # attach ru under rv: pos(ru) relative to rv
            parent[ru] = rv
            disp[ru] = (vx - sx - ux, vy - sy - uy)
            if ru in windings:
                windings.setdefault(rv, []).extend(windings.pop(ru))
    out = []
    for ws in windings.values():
        g = 0
        for (wx, wy) in ws:
            g = gcd(g, gcd(abs(wx), abs(wy)))
        # rank: all windings parallel?
        base = ws[0]
        rank2 = any(base[0] * w[1] - base[1] * w[0] != 0 for w in ws)
        if rank2:
            out.append(("cross-or-rank-2", None))
        else:
            k = gcd(abs(base[0]), abs(base[1]))
            out.append(("winding", (base[0] // k, base[1] // k)))
    return out


# ------------------------------------------------------------------ Pinson's winding probabilities

def eta(q, terms=400):
    prod = 1.0
    for k in range(1, terms):
        t = q ** k
        prod *= 1 - t
        if t < 1e-18:
            break
    return q ** (1 / 24) * prod


_ETA = {}


def Zmn(m, n, g, r):
    if r not in _ETA:
        _ETA[r] = eta(math.exp(-2 * math.pi * r))
    return math.sqrt(g) / (math.sqrt(r) * _ETA[r] ** 2) * math.exp(-math.pi * g * (m * m / r + n * n * r))


def P_winding(a, b, r, L=60):
    g = 2 / 3
    s = lambda f: sum(f(l) for l in range(-L, L + 1))
    return (s(lambda l: Zmn(3 * l * a, 3 * l * b, g, r)) - 0.5 * s(lambda l: Zmn((3 * l + 1) * a, (3 * l + 1) * b, g, r))
            - 0.5 * s(lambda l: Zmn((3 * l + 2) * a, (3 * l + 2) * b, g, r)) - s(lambda l: Zmn(2 * l * a, 2 * l * b, g, r))
            + s(lambda l: Zmn((2 * l + 1) * a, (2 * l + 1) * b, g, r)))


def P_cross(r, M=40):
    zc = lambda g, f: f * sum(Zmn(f * m, f * n, g, r) for m in range(-M, M + 1) for n in range(-M, M + 1))
    return 0.5 * (zc(8 / 3, 1.0) - zc(8 / 3, 0.5))


def normalized(maxw=40):
    out = [(1, 0), (0, 1)]
    for a in range(1, maxw + 1):
        for b in range(-maxw, maxw + 1):
            if b != 0 and gcd(a, abs(b)) == 1:
                out.append((a, b))
    return out


def pinson_prediction(r, parity, drop_cross=False):
    """r = vertical / horizontal circumference; parity(a, b) = 1 when a cycle with a horizontal and b vertical windings is odd."""
    px = 0.0 if drop_cross else P_cross(r)
    p0 = P_cross(r)
    wind = {w: P_winding(*w, r) for w in normalized()}
    total = p0 + px + sum(wind.values())
    inconsistent = px + sum(p for w, p in wind.items() if parity(*w))
    return {"P_all_contractible": p0, "P_cross": px, "P_winding_1_0": wind[(1, 0)], "P_winding_0_1": wind[(0, 1)],
            "P_winding_1_1": wind[(1, 1)], "sum_over_topologies": total, "P_consistent": 1 - inconsistent,
            "E_bits": -math.log2(1 - inconsistent)}


# ------------------------------------------------------------------ the checks

def run():
    checks, controls, failures = {}, {}, []
    rng = random.Random("contact-census")

    # Theorem 1: classes
    K = knots3()
    classes = {}
    for R in K:
        for a, b in ((0, 1), (0, 2), (1, 2), (1, 0), (2, 0), (2, 1)):
            classes.setdefault(canonical(transfers(R, a, b)), []).append(transfers(R, a, b))
    counts = {"+".join(c): len(v) for c, v in sorted(classes.items())}
    nv32, e32, _ = torus(3, 2)
    same_law = {}
    for c, pairs in classes.items():
        values = {count_consistent(nv32, e32, p) for p in set(pairs)}
        same_law["+".join(c)] = sorted(values)
    checks["theorem_1_classes"] = {"knots": len(K), "placements": sum(counts.values()), "classes": counts,
                                   "consistent_patterns_on_3x2_torus_per_class": same_law}
    if not (len(K) == 34 and sum(counts.values()) == 204 and len(counts) == 10 and all(len(v) == 1 for v in same_law.values())):
        failures.append("Theorem 1")

    def vacuum(pair):
        return any(all(M[c][c] for M in pair) for c in (0, 1))
    reps = {"+".join(c): v[0] for c, v in classes.items()}

    # Theorem 2: vacuum classes hold nothing
    vac = {}
    for name, pair in reps.items():
        if not vacuum(pair):
            continue
        ok = count_consistent(nv32, e32, pair) == 2 ** len(e32)
        for _ in range(50):
            n = rng.randint(3, 9)
            edges = [(u, v) for u in range(n) for v in range(u + 1, n) if rng.random() < 0.5]
            if not edges:
                continue
            ok &= all(consistent(n, edges, [pair[rng.randrange(2)] for _ in edges]) for _ in range(20))
        vac[name] = ok
    checks["theorem_2_vacuum_classes"] = vac
    if not (len(vac) == 6 and all(vac.values())):
        failures.append("Theorem 2")

    # Theorems 3 and 4: patches
    patches = {}
    for name, pair in reps.items():
        found = None
        for m, n in ((2, 2), (2, 3), (3, 3), (2, 4), (3, 4)):
            nv, edges = grid(m, n)
            bad = 2 ** len(edges) - count_consistent(nv, edges, pair)
            if bad:
                found = [m, n, bad, 2 ** len(edges)]
                break
        patches[name] = found
    parity_pair = reps["I+S"]
    nv33, e33, _ = torus(3, 3)
    parity_consistent = count_consistent(nv33, e33, parity_pair)
    b1 = len(e33) - nv33 + 1
    nv44, e44, _ = torus(4, 4)
    even_ok = {name: all(consistent(nv44, e44, [reps[name][rng.randrange(2)] for _ in e44]) for _ in range(2000))
               for name in ("A1+A2", "J+S")}
    checks["theorem_3_4_patches"] = {"smallest_frustrating_grid": patches,
                                     "parity_on_3x3_torus": {"consistent": parity_consistent, "patterns": 2 ** len(e33),
                                                             "cycle_rank": b1},
                                     "critical_classes_on_even_4x4_torus_always_consistent": even_ok}
    if not (patches["I+S"] == [2, 2, 8, 16] and patches["L+S"] == [2, 3, 8, 128] and patches["A1+A2"] is None
            and patches["J+S"] is None and parity_consistent * 2 ** b1 == 2 ** len(e33) and all(even_ok.values())
            and all(patches[n] is None for n in vac)):
        failures.append("Theorems 3-4")

    # Theorem 5: x or (h != h') is bipartite percolation, classified by windings
    or_neq = reps["J+S"]
    zero_spoke = 0 if or_neq[0] == S else 1          # the spoke value whose transfer is h != h'
    red = {}
    for (a, b, sample) in ((3, 3, None), (5, 5, 20000), (3, 4, 20000), (5, 6, 20000)):
        nv, edges, steps = torus(a, b)
        stats = Counter()
        patterns = product((0, 1), repeat=len(edges)) if sample is None else \
            (tuple(rng.randrange(2) for _ in edges) for _ in range(sample))
        for xs in patterns:
            ok = consistent(nv, edges, [or_neq[x] for x in xs])
            open_mask = [x == zero_spoke for x in xs]
            bip = bipartite_parity(nv, edges, open_mask)
            classes_found = winding_classes(nv, edges, steps, open_mask, a, b)
            # parity of a cycle with windings (wx, wy): wx * b + wy * a (mod 2)
            odd = any(kind == "cross-or-rank-2" or (w[0] * b + w[1] * a) % 2 == 1 for kind, w in classes_found)
            stats["patterns"] += 1
            stats["consistent equals bipartite"] += ok == bip
            stats["bipartite equals no odd topology"] += bip == (not odd)
            stats["inconsistent"] += not ok
            stats["has wrapping cluster"] += bool(classes_found)
        red[f"{a}x{b}"] = dict(stats)
    checks["theorem_5_bipartite_percolation"] = red
    if not all(v["consistent equals bipartite"] == v["patterns"] == v["bipartite equals no odd topology"]
               and v["inconsistent"] > 0 for v in red.values()):
        failures.append("Theorem 5")

    # Pinson's formula: reference values and predictions
    sq = pinson_prediction(1.0, lambda a, b: (a + b) % 2)
    preds = {
        "square, both sides odd (r = 1)": sq,
        "rows odd, columns twice as many (r = 1/2)": pinson_prediction(0.5, lambda a, b: b % 2),
        "rows twice the odd columns (r = 2)": pinson_prediction(2.0, lambda a, b: a % 2),
        "rows 3k odd, columns 2k (r = 3/2)": pinson_prediction(1.5, lambda a, b: b % 2),
        "both odd, rows 3/5 of columns (r = 3/5)": pinson_prediction(0.6, lambda a, b: (a + b) % 2),
    }
    reference = {"P_all_contractible_r1": round(sq["P_all_contractible"], 9), "P_winding_1_0_r1": round(sq["P_winding_1_0"], 9),
                 "newman_ziff_1_minus_Re": 0.309526275, "newman_ziff_R1": 0.169415435}
    checks["pinson"] = {"reference": reference,
                        "predictions": {k: {kk: round(vv, 9) for kk, vv in v.items()} for k, v in preds.items()}}
    if not (abs(sq["P_all_contractible"] - 0.309526275) < 2e-9 and abs(sq["P_winding_1_0"] - 0.169415435) < 2e-9
            and all(abs(v["sum_over_topologies"] - 1) < 1e-8 for v in preds.values())):
        failures.append("Pinson")

    # Controls
    controls["swap_or_order_has_a_vacuum"] = "accepted" if vacuum(reps["L+S"]) else "rejected"
    controls["not_all_equal_frustrated_by_a_face"] = "accepted" if patches["A1+A2"] == [2, 2] else "rejected"
    nv44w, e44w, s44w = torus(4, 4)
    wrap_seen = False
    for _ in range(3000):
        xs = [rng.randrange(2) for _ in e44w]
        mask = [x == zero_spoke for x in xs]
        if winding_classes(nv44w, e44w, s44w, mask, 4, 4):
            wrap_seen = True
            if not consistent(nv44w, e44w, [or_neq[x] for x in xs]):
                wrap_seen = False
                break
    controls["consistency_ignores_winding_parity"] = "rejected" if wrap_seen else "accepted"
    wrong = pinson_prediction(1.0, lambda a, b: (a + b) % 2, drop_cross=True)
    controls["pinson_sums_to_one_without_the_cross_term"] = (
        "accepted" if abs(wrong["sum_over_topologies"] - 1) < 1e-6 else "rejected")
    if any(v != "rejected" for v in controls.values()):
        failures.append("controls")
    checks["theorem_6_bounds"] = ("argued-in-prose: crossing bounds and positive correlation give a cross cluster and a "
                                  "fully contractible configuration each with probability bounded below at fixed shape")
    return checks, controls, failures


def main() -> int:
    write = "--write" in sys.argv[1:]
    checks, controls, failures = run()
    manifest = json.loads((HERE / "manifest.json").read_text())
    result = {
        "schema_version": 3, "artifact_id": manifest["artifact_id"], "kind": "proof", "ticket": manifest["ticket"],
        "proof": manifest["proof"], "status": "passed" if not failures else "failed", "claim": manifest["claim"],
        "foundation_contract": manifest["foundation_contract"], "semantic_domains": manifest["semantic_domains"],
        "evidence_modes": manifest["evidence_modes"], "thesis_alignment": manifest["thesis_alignment"],
        "safe_conclusions": manifest["safe_to_conclude"], "checks": checks, "controls": controls, "failures": failures,
    }
    path = HERE / "result.json"
    text = json.dumps(result, indent=2, sort_keys=True, ensure_ascii=False, default=str) + "\n"
    if write:
        path.write_text(text)
    elif not path.exists() or json.loads(path.read_text()) != json.loads(text):
        print("result.json does not match a fresh run; rerun with --write after review")
        return 1
    print(f"{result['status']}: failures {failures}")
    return 0 if not failures else 1


if __name__ == "__main__":
    raise SystemExit(main())
