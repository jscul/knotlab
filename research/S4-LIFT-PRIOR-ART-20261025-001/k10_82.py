def gauss_from_pd(pd):
    n2 = 2 * len(pd)
    nxt = lambda e: e % n2 + 1
    visit = {}
    for c, (i, j, k, l) in enumerate(pd):
        assert k == nxt(i)
        visit[i] = (c, False)                          # edge i enters crossing c as the under strand
        if j == nxt(l):
            visit[l] = (c, True); sign = 1             # over strand runs l -> j: positive
        else:
            assert l == nxt(j)
            visit[j] = (c, True); sign = -1
        visit.setdefault(("s", c), sign)
    return [(visit[e][0], visit[e][1], visit[("s", visit[e][0])]) for e in range(1, n2 + 1)]

def stats(code, name):
    U, cr = B.wirtinger(code)
    per = defaultdict(lambda: [0, Counter()])
    for vals, lam in B.colourings(U, cr, B.T0):
        per[tuple(B.pairing_of(v) for v in vals)][0] += 1
    for vals, lam in B.colourings(U, cr, B.C0):
        per[tuple(B.pairing_of(v) for v in vals)][1][lam] += 1
    # surjective homs onto S4 with transposition / 4-cycle meridians (all meridian values), up to conjugacy
    def surj_classes(cls):
        tot = 0
        for m in cls:
            for vals, lam in B.colourings(U, cr, m):
                # image generated by arc values
                gen = set(vals); grp = {B.E0}; frontier = [B.E0]
                while frontier:
                    g = frontier.pop()
                    for s in gen:
                        h = B.MUL[g][s]
                        if h not in grp:
                            grp.add(h); frontier.append(h)
                tot += len(grp) == 24
        return tot / 24
    print(name, "crossings", len(cr), "| per S3 colouring (fixed meridian): ",
          [(t, {("1" if l == B.E0 else "c^2"): n for l, n in lg.items()}) for t, lg in per.values()],
          "| surjective S4 classes: simple", surj_classes(B.CLASSES[(2, 1, 1)]), "cyclic", surj_classes(B.CLASSES[(4,)]))

