"""Check actual changes, family descendants, and the two readings of small change.

A family-even change on the start is generated by shared-only start cycles,
pairs of loose distinctions at a single parent, and the two loose inputs
selected by a joint birth together with their two meetings through an old
witness. These loose pairs connect all the individual loose distinctions in
each family. Subtracting their generators leaves a shared-only start change.
The same-parent pair closes permanently through two siblings and their common
child. The joint-birth generator closes at that birth. Each lift has size at
most four. Thus an outside start parity flips within max(4, #start knots).

For k >= 4 and t >= max(2, floor(k/2)), a simple change of size <= k that
meets the start cannot also reach a newest loose distinction: going out and
back costs at least 2(t+1). In a closed walk, replace a highest-round visit
through a child of u,v by a visit through an older common witness of u,v.
The length does not increase. The difference projects to a joint-birth
generator at height one, a same-parent pair at height two, and zero higher.
Different choices of inputs or common witness add same-parent pairs or a
shared-only start cycle of size at most four. The surviving closed start
walk splits into simple start cycles of size <= k. The permanent generators
and those small shared-only start cycles therefore give the projected span.
"""

import argparse
import itertools
import json
import random
import resource
import time
from collections import Counter, defaultdict, deque
from pathlib import Path

import growth


HERE = Path(__file__).resolve().parent
SEED = 2026112601


def mask(distinctions):
    return sum(1 << d for d in distinctions)


def members(vector):
    while vector:
        bit = vector & -vector
        yield bit.bit_length() - 1
        vector ^= bit


def basis(vectors):
    rows = {}
    for x in vectors:
        while x:
            top = x.bit_length()
            if top not in rows:
                rows[top] = x
                break
            x ^= rows[top]
    return rows


def rank(vectors):
    return len(basis(vectors))


def equal_spans(a, b):
    return rank(a) == rank(b) == rank(itertools.chain(a, b))


class Incidence:
    """One auxiliary holder completes all loose distinctions for counting changes."""

    def __init__(self, supports):
        self.laws = [mask(row) for row in supports]
        self.boundary = len(supports)
        holders = defaultdict(list)
        for knot, row in enumerate(supports):
            for d in row:
                holders[d].append(knot)
        self.loose = {d for d, ends in holders.items() if len(ends) == 1}
        self.ends = {d: tuple(ends + ([self.boundary] if d in self.loose else []))
                     for d, ends in holders.items()}
        self.adj = [[] for _ in range(len(supports) + 1)]
        for d, (u, v) in self.ends.items():
            self.adj[u].append((v, d))
            self.adj[v].append((u, d))
        self.dimension = len(self.ends) - rank(self.laws)

    def allows(self, vector):
        parity = Counter(k for d in members(vector) for k in self.ends[d])
        return all(count % 2 == 0 for count in parity.values())

    def cycles(self, limit, closed_start=False):
        """All simple cycles, including a pair with the same two holders."""
        found = set()
        for root, links in enumerate(self.adj):
            last = self.boundary if closed_start else self.boundary + 1
            if root >= last:
                break
            stack = [(v, 1 << d, (1 << root) | (1 << v), 1)
                     for v, d in links if root < v < last]
            while stack:
                u, path, visited, length = stack.pop()
                for v, d in self.adj[u]:
                    bit = 1 << d
                    if path & bit:
                        continue
                    if v == root:
                        found.add(path | bit)
                    elif length + 1 < limit and root < v < last and not visited & (1 << v):
                        stack.append((v, path | bit, visited | (1 << v), length + 1))
        return found

    def flip(self, fact):
        """Least f-odd closed walk by deleting one marked distinction at a time."""
        best = None
        for d in members(fact):
            u, v = self.ends[d]
            first = (u, 0)
            pending = deque([first])
            path = {first: ()}
            while pending:
                vertex, sign = pending.popleft()
                route = path[vertex, sign]
                if vertex == v and sign == 0:
                    walk = (d,) + route
                    if best is None or len(walk) < len(best):
                        best = walk
                    break
                if best and len(route) + 2 >= len(best):
                    continue
                for neighbor, step in self.adj[vertex]:
                    if step == d:
                        continue
                    state = (neighbor, sign ^ ((fact >> step) & 1))
                    if state not in path:
                        path[state] = route + (step,)
                        pending.append(state)
        if best is not None:
            assert len(set(best)) == len(best)
            assert self.allows(mask(best)) and (mask(best) & fact).bit_count() % 2
        return best

    def shared_basis(self):
        """A basis for all changes using only shared distinctions of this stage."""
        root_paths = {}
        for root in range(self.boundary):
            if root in root_paths:
                continue
            root_paths[root] = 0
            pending = deque([root])
            while pending:
                u = pending.popleft()
                for v, d in self.adj[u]:
                    if v == self.boundary or v in root_paths:
                        continue
                    root_paths[v] = root_paths[u] ^ (1 << d)
                    pending.append(v)
        cycles = []
        for d, (u, v) in self.ends.items():
            if d not in self.loose:
                cycle = root_paths[u] ^ root_paths[v] ^ (1 << d)
                if cycle:
                    cycles.append(cycle)
        assert len(cycles) == rank(cycles)
        assert all(c.bit_count() <= self.boundary for c in cycles)
        return cycles


def construct(n, links, openings):
    rows = [[] for _ in range(n)]
    names = itertools.count()
    for a, b in links:
        d = next(names)
        rows[a].append(d)
        rows[b].append(d)
    for row, count in zip(rows, openings, strict=True):
        row.extend(next(names) for _ in range(count))
    return tuple(tuple(row) for row in rows)


def ring(n, openings=None, double=False):
    links = [(v, (v + 1) % n) for v in range(n)] * (2 if double else 1)
    return construct(n, links, openings if openings is not None else [2] * n)


def extra_starts(count):
    rng = random.Random(SEED)
    for i in range(count):
        n = (7, 8, 11, 14)[i % 4]
        basic = {tuple(sorted((v, (v + 1) % n))) for v in range(n)}
        links = []
        for pair in itertools.combinations(range(n), 2):
            if pair in basic or rng.random() < 0.07:
                links.extend([pair] * (1 + (rng.random() < 0.2)))
        if i % 3:
            _, groups, _ = growth.proposals(construct(n, links, [1] * n))
            demand = Counter(k for group in groups for k in group)
            openings = [max(1, demand[k]) + (rng.random() < 0.15) for k in range(n)]
        else:
            openings = [rng.randint(1, 2) for _ in range(n)]
        yield f"labelled draw {i} with {n} knots", construct(n, links, openings)


def local_generators(rows, first, second):
    """Return a start change, a round-one lift and a permanently closed lift."""
    old = Incidence(rows)
    loose = defaultdict(list)
    by_pair = defaultdict(list)
    for d, (u, v) in old.ends.items():
        if d in old.loose:
            loose[u].append(d)
        else:
            by_pair[min(u, v), max(u, v)].append(d)
    birth_for = {d: b for b in first for d in b["inputs"]}
    lifts = []
    for ds in loose.values():
        for x, y in itertools.combinations(ds, 2):
            old_pair = mask([x, y])
            if not first:
                lifts.append(("same holder", old_pair, None, None))
                continue
            p, q = birth_for[x], birth_for[y]
            assert p["knot"] != q["knot"]
            t1 = old_pair | mask([p["fresh"][0], q["fresh"][0]])
            t2 = None
            if second:
                c = next(b for b in second if {p["knot"], q["knot"]} <= set(b["parents"]))
                x1, = set(c["inputs"]) & set(p["fresh"])
                y1, = set(c["inputs"]) & set(q["fresh"])
                t2 = old_pair | mask([x1, y1])
            lifts.append(("same holder", old_pair, t1, t2))
    for w in range(old.boundary):
        neighbors = {v for v, _ in old.adj[w] if v in loose}
        for a, b in itertools.combinations(sorted(neighbors), 2):
            if first:
                child = next(c for c in first if {a, b} <= set(c["parents"]))
                x, = set(child["inputs"]) & set(loose[a])
                y, = set(child["inputs"]) & set(loose[b])
            else:
                x, y = loose[a][0], loose[b][0]
            z = mask([x, y, by_pair[min(a, w), max(a, w)][0], by_pair[min(b, w), max(b, w)][0]])
            lifts.append(("common witness", z, z if first else None, z if first else None))
    return lifts


def classes(inc, start, cycles, start_mask):
    return {"dimension": inc.dimension - rank(cycles),
            "start_dimension": start.dimension - rank(c & start_mask for c in cycles)}


def scale_profile(inc, start, at, scales, generators, start_mask, closed_small):
    # Finding the least through each individual distinction verifies the cycle-enumeration
    # limit covers every tied shortest move, even when the minimum is above the top scale.
    minimum = {d: len(inc.flip(1 << d) or ()) for d in inc.ends}
    cycles = inc.cycles(max(max(scales), max(minimum.values(), default=0)))
    assert all(not minimum[d] or min(c.bit_count() for c in cycles if c & (1 << d)) == minimum[d]
               for d in inc.ends)
    shortest = {c for c in cycles if any(minimum[d] == c.bit_count() for d in members(c))}
    short = classes(inc, start, shortest, start_mask)
    short.update({"tied_changes": len(shortest), "largest_shortest": max(minimum.values(), default=0)})
    readings = {}
    for k in scales:
        small = {c for c in cycles if c.bit_count() <= k}
        result = classes(inc, start, small, start_mask)
        if k >= 4 and at >= max(2, k // 2):
            predicted = generators + [c for c in closed_small if c.bit_count() <= k]
            assert equal_spans([c & start_mask for c in small], predicted)
            assert result["dimension"] == result["start_dimension"]
            result["permanent_start_generators_exact"] = True
        readings[str(k)] = result
    return readings, short, shortest, cycles


def trajectory(name, rows, rounds, cap, scales=(), odd_ring=False):
    start = Incidence(rows)
    start_mask = mask(start.ends)
    start_families, groups = growth.families(rows)
    family_facts = list(map(mask, groups))
    family_rank = rank(start.laws + family_facts) - rank(start.laws)
    shared = start.shared_basis()
    closed_small = start.cycles(max(scales), closed_start=True) if scales else ()
    stages = list(growth.stages(rows, rounds, cap))
    first = stages[1][3] if len(stages) > 1 else ()
    second = stages[2][3] if len(stages) > 2 else ()
    local = local_generators(rows, first, second)
    projections = [z for _, z, _, _ in local]
    assert rank(shared + projections) == start.dimension - family_rank
    assert all(not ((v & f).bit_count() % 2) for v in shared + projections for f in family_facts)
    labels = {k: i for i, group in enumerate(start_families) for k in group}
    result = {"name": name, "start_family_rank": family_rank, "start_families": len(groups),
              "outside_tested_by_kernel_rank": start.dimension - family_rank,
              "uniform_outside_upper_bound": max([4] + [x.bit_count() for x in shared]),
              "local_generators": dict(Counter(kind for kind, *_ in local)),
              "closed_basis_sizes": [x.bit_count() for x in shared], "stages": []}
    loose_example = min(start.loose, default=None)
    shared_fact = mask(d for d in start.ends if d not in start.loose) if odd_ring else 0
    for at, supports, status, births in stages:
        if status != "stage":
            result["stop"] = status
            break
        inc = Incidence(supports)
        if at:
            for b in births:
                families = {labels[parent] for parent in b["parents"]}
                assert len(families) == 1
                labels[b["knot"]] = families.pop()
        actual, _ = growth.families(supports)
        classes_now = [{labels[k] for k in family} for family in actual]
        assert all(len(ids) == 1 for ids in classes_now)
        assert not actual or {i for ids in classes_now for i in ids} == set(range(len(groups)))
        assert len(actual) == len(set(i for ids in classes_now for i in ids))
        lift_index = min(at, 2) + 1
        for lift in local:
            z = lift[lift_index]
            assert z is not None and inc.allows(z) and (z & start_mask) == lift[1]
            if at >= 2:
                assert all(d not in inc.loose for d in members(z))
        assert all(inc.allows(z) for z in shared)
        state = {"round": at, "knots": len(supports), "distinctions": len(inc.ends),
                 "families": len(actual), "births": len(births), "verified_lifts": len(local) + len(shared)}
        if scales:
            readings, short, shortest, cycles = scale_profile(
                inc, start, at, scales, projections, start_mask, closed_small)
            state.update({"up_to": readings, "shortest": short})
            if odd_ring:
                flip = inc.flip(shared_fact)
                assert len(flip) == min(len(rows), 3 + 2 * at)
                short_preserves = all((c & shared_fact).bit_count() % 2 == 0 for c in shortest)
                assert short_preserves == (at >= 1)
                if at:
                    for k in ("2", "3"):
                        assert readings[k]["dimension"] == len(rows) * (at + 1)
                        assert readings[k]["start_dimension"] == 2 * len(rows)
                state["shared_start_parity"] = {"least": len(flip), "kept_by_all_tied_shortest": short_preserves}
                if name == "five-knot ring" and at == 2:
                    loose_flip = inc.flip(1 << loose_example)
                    assert len(loose_flip) == 4
                    small_mask = 0
                    for c in cycles:
                        if c.bit_count() <= 3:
                            small_mask |= c
                    fresh = next(d for d in sorted(inc.ends) if d not in start.ends and not small_mask & (1 << d)
                                 and any(c & (1 << d) and not c & start_mask for c in cycles))
                    fresh_change = min((c for c in cycles if c & (1 << fresh) and not c & start_mask),
                                       key=lambda c: (c.bit_count(), c))
                    assert fresh_change.bit_count() == 4
                    result["scale_counterexamples"] = {
                        "support_rows": supports, "original_loose_fact": loose_example,
                        "four_change_flipping_original_loose": loose_flip,
                        "late_distinction_kept_through_size_three": fresh,
                        "four_change_flipping_it_while_start_fixed": list(members(fresh_change)),
                        "start_knots": len(rows)}
        result["stages"].append(state)
    result.setdefault("stop", "requested last round")
    return result


def run(pilot):
    scales = (2, 3, 4, 5, 6, 8)
    tasks = [
        ("five-knot ring", ring(5), 16, 350, scales, True),
        ("seventeen-knot ring", ring(17), 11, 500, scales, True),
        ("ten-knot ring with two families", ring(10), 13, 340, scales, False),
        ("twenty-four-knot ring", ring(24), 12, 800, (), False),
        ("six-knot ring with three-parent births", ring(6), 8, 400, (), False),
        ("nine-knot ring short of one loose distinction", ring(9, [1] + [2] * 8), 8, 260, scales, False),
        ("single three-place knot", ((0, 1, 2),), 6, 260, scales, False),
        ("closed five-knot ring with double meetings", ring(5, [0] * 5, True), 6, 260, scales, False),
        ("fourteen-knot three-ring start", growth.fourteen_start()[0], 8, 400, (2, 3, 4, 5, 6), False),
        ("three rings of seven with split attachments", growth.ring_start(3, 7, "split", "double")[0],
         9, 550, (), False)]
    if pilot:
        tasks = [(name, rows, min(rounds, 3), cap, ks, odd) for name, rows, rounds, cap, ks, odd in tasks]
    tasks.extend((name, rows, 3 if pilot else 7, 280, (), False)
                 for name, rows in extra_starts(3 if pilot else 36))
    output = []
    for name, rows, rounds, cap, ks, odd in tasks:
        begin = time.perf_counter()
        output.append(trajectory(name, rows, rounds, cap, ks, odd))
        output[-1]["seconds"] = round(time.perf_counter() - begin, 4)
    return {"pilot": pilot, "random_seed": SEED,
            "draw_weighting": "cycle with independently added meetings, optional doubled meetings; two of every three draws fund every group with an optional spare",
            "bounds": {"random_draw_rounds": 3 if pilot else 7, "random_draw_distinctions": 280,
                       "profiles": list(scales), "processes": 1, "memory_gib": 2},
            "cases": output}


if __name__ == "__main__":
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--pilot", action="store_true")
    args = cli.parse_args()
    resource.setrlimit(resource.RLIMIT_AS, (2 << 30, 2 << 30))
    record = run(args.pilot)
    summary = {"starts": len(record["cases"]),
               "stages": sum(len(row["stages"]) for row in record["cases"]),
               "seconds": round(sum(row["seconds"] for row in record["cases"]), 3),
               "slowest_cases": sorted(((e["seconds"], e["name"]) for e in record["cases"]), reverse=True)[:4]}
    print(json.dumps(summary))
    if not args.pilot:
        (HERE / "split_counts.json").write_text(json.dumps(record, indent=2) + "\n")
