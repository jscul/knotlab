    for i in range(4):
        algebras.append((f"random Mal'tsev on 3 elements {i}", 3, [(3, random_maltsev(rng, 3))]))
    for i in range(3):
        algebras.append((f"random Mal'tsev on 4 elements {i}", 4, [(3, random_maltsev(rng, 4))]))
    lem2 = {"relations": 0, "rectangular": 0}
    thm1 = {}
    for name, q, ops in algebras:
        holds, witness = condition(q, ops)
        row = {"condition_holds": holds, "subalgebras_sampled": 0, "proper": 0, "failures": 0, "mechanism_ok": 0}
        if not holds:
            B, c1, c2 = witness
            S = {(x, e, z) for x in B for e in B for z in B if c1[x] == c1[e] and c2[e] == c2[z]}
