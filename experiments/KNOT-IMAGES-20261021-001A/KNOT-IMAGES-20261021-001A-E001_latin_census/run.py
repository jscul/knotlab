# ------------------------------------------------------------------ Latin squares

def cayley(elems, mul):
    idx = {e: i for i, e in enumerate(elems)}
    return [[idx[mul(a, b)] for b in elems] for a in elems]


def random_latin(n, rng):
    while True:
        rows = []
        for _ in range(n):
            for _ in range(500):
                r = list(range(n))
                rng.shuffle(r)
                if all(r[j] != row[j] for row in rows for j in range(n)):
                    rows.append(r)
                    break
            else:
                break
        if len(rows) == n:
            return rows


def group_isotope(L):
    n = len(L)
    rinv = {L[a][0]: a for a in range(n)}
    cinv = {L[0][b]: b for b in range(n)}
    op = lambda x, y: L[rinv[x]][cinv[y]]
    return all(op(op(x, y), z) == op(x, op(y, z)) for x in range(n) for y in range(n) for z in range(n))


def net(L):
    n = len(L)
    return {"sorts": [n, n, n], "rels": [((0, 1, 2), sorted((i, j, L[i][j]) for i in range(n) for j in range(n)))],
            "family": "3-net", "square": L, "group_isotope": group_isotope(L)}


