def generate(gens, ops, n):
    """Subalgebra of A^n generated by gens under ops (each op: (arity, function))."""
    S = set(gens)
    frontier = set(gens)
    while frontier:
        new = set()
        items = list(S)
        for arity, f in ops:
            for args in product(items, repeat=arity):
                if not any(a in frontier for a in args):
                    continue
                t = tuple(f(*cols) for cols in zip(*args))
                if t not in S:
                    new.add(t)
        S |= new
        frontier = new
    return S


def subuniverses(q, ops):
    out = []
    for mask in range(1, 1 << q):
        B = [x for x in range(q) if mask >> x & 1]
        Bs = set(B)
        if all(f(*args) in Bs for arity, f in ops for args in product(B, repeat=arity)):
            out.append(tuple(B))
    return out


def partitions(items):
    items = list(items)
    if not items:
        yield []
        return
    first, rest = items[0], items[1:]
    for p in partitions(rest):
        for i in range(len(p)):
            yield p[:i] + [[first] + p[i]] + p[i + 1:]
        yield [[first]] + p


def congruences(B, ops):
    out = []
    for p in partitions(B):
        cls = {x: i for i, block in enumerate(p) for x in block}
        if all(cls[f(*a)] == cls[f(*b)] for arity, f in ops for a in product(B, repeat=arity)
               for b in product(B, repeat=arity) if all(cls[x] == cls[y] for x, y in zip(a, b))):
            out.append(cls)
    return out


def condition(q, ops):
    """Every subuniverse with at least 2 elements has a unique maximal proper congruence; returns (holds, witness)."""
    for B in subuniverses(q, ops):
        if len(B) < 2:
            continue
        cons = congruences(B, ops)
        proper = [c for c in cons if len(set(c.values())) > 1]
        def finer(a, b):
            return all(a[x] != a[y] or b[x] == b[y] for x in B for y in B)
        maximal = [c for c in proper if not any(d != c and finer(c, d) for d in proper)]
        if len(maximal) >= 2:
            return False, (B, maximal[0], maximal[1])
    return True, None


def random_maltsev(rng, q):
    table = {}
    for x, y, z in product(range(q), repeat=3):
        if x == y:
            table[(x, y, z)] = z
        elif y == z:
            table[(x, y, z)] = x
        else:
            table[(x, y, z)] = rng.randrange(q)
    return lambda x, y, z: table[(x, y, z)]


def linked(R1, e_index, B):
    """g ~ g' when some assignment to the other coordinates of R1 allows both."""
    by_rest = {}
    for t in R1:
        rest = tuple(v for i, v in enumerate(t) if i != e_index)
        by_rest.setdefault(rest, set()).add(t[e_index])
    pairs = {(g, h) for vals in by_rest.values() for g in vals for h in vals}
    return pairs


def mechanism_holds(S, n, C1, C2, e, ops):
    De = sorted({t[e] for t in S})
    rels = []
    for C in (C1, C2):
        cols = list(C)
        R = {tuple(t[i] for i in cols) for t in S}
        rels.append(linked(R, cols.index(e), De))
    g1, g2 = rels
    total = {(x, y) for x in De for y in De}
    for g in (g1, g2):
        if g == total:
            return False
        cls = {}
        for x in De:
            cls[x] = frozenset(y for y in De if (x, y) in g)
        if any((x, y) in g and cls[x] != cls[y] for x in De for y in De):
            return False
        if not all(f(*a) in De for arity, f in ops for a in product(De, repeat=arity)):
            return False
        if not all((f(*a), f(*b)) in g for arity, f in ops for a in product(De, repeat=arity)
                   for b in product(De, repeat=arity) if all((x, y) in g for x, y in zip(a, b))):
            return False
    comp = {(x, z) for x, y in g1 for y2, z in g2 if y == y2}
    return comp == total


