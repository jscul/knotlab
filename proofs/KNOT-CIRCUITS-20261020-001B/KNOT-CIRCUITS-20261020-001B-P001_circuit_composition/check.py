def q8(a, b):
    table = {("1", u): (1, u) for u in "1ijk"}
    table.update({(u, "1"): (1, u) for u in "1ijk"})
    table.update({("i", "i"): (-1, "1"), ("j", "j"): (-1, "1"), ("k", "k"): (-1, "1"), ("i", "j"): (1, "k"),
                  ("j", "k"): (1, "i"), ("k", "i"): (1, "j"), ("j", "i"): (-1, "k"), ("k", "j"): (-1, "i"),
                  ("i", "k"): (-1, "j")})
    s, u = table[(a[1], b[1])]
    return (a[0] * b[0] * s, u)


def group_tables(elems):
    ix = {p: i for i, p in enumerate(elems)}
    deg = len(elems[0])
    n = len(elems)
    mul = [[ix[tuple(elems[a][elems[b][i]] for i in range(deg))] for b in range(n)] for a in range(n)]
    ident = ix[tuple(range(deg))]
    inv = [next(b for b in range(n) if mul[a][b] == ident) for a in range(n)]
    return mul, inv, ident


def subgroups(mul, ident, n):
    subs = {frozenset({ident})}
    for gens in combinations(range(n), 2):
        H = {ident}
        frontier = [ident]
        while frontier:
            new = []
            for h in frontier:
                for g in gens:
                    x = mul[h][g]
                    if x not in H:
                        H.add(x)
                        new.append(x)
            frontier = new
        subs.add(frozenset(H))
    for g in range(n):
        H = {ident}
        x = g
        while x not in H:
            H.add(x)
            x = mul[x][g]
        subs.add(frozenset(H))
    changed = True
    while changed:
        changed = False
        for A, B in combinations(list(subs), 2):
            H = set(A | B)
            frontier = list(H)
            while frontier:
                new = []
                for h in frontier:
                    for g in list(A | B):
                        x = mul[h][g]
                        if x not in H:
                            H.add(x)
                            new.append(x)
                frontier = new
            if frozenset(H) not in subs:
                subs.add(frozenset(H))
                changed = True
    return subs


def group_condition(mul, inv, ident, n):
    subs = subgroups(mul, ident, n)
    for H in sorted(subs, key=len):
        if len(H) < 2:
            continue
        normal = [N for N in subs if N < H and all(mul[mul[h][x]][inv[h]] in N for h in H for x in N)]
        maximal = [N for N in normal if not any(N < M for M in normal)]
        if len(maximal) >= 2:
            return False, (H, maximal[0], maximal[1]), len(subs)
    return True, None, len(subs)


def random_coset(rng, mul, inv, ident, n, dim):
    T = [tuple(rng.randrange(n) for _ in range(dim)) for _ in range(rng.randint(2, 4))]
    t0 = T[0]
    gens = [tuple(mul[a][inv[b]] for a, b in zip(t, t0)) for t in T[1:]]
    H = {tuple([ident] * dim)}
    frontier = list(H)
    while frontier:
        new = []
        for h in frontier:
            for g in gens:
                x = tuple(mul[a][b] for a, b in zip(h, g))
                if x not in H:
                    H.add(x)
                    new.append(x)
        frontier = new
    return {tuple(mul[a][b] for a, b in zip(h, t0)) for h in H}


def field(q):
    if q == 5:
        return (lambda a, b: (a + b) % 5), (lambda a, b: (a * b) % 5)
    exp = [1, 2, 3]

    def mul(a, b):
        if a == 0 or b == 0:
            return 0
        return exp[(exp.index(a) + exp.index(b)) % 3]

    return (lambda a, b: a ^ b), mul


def random_affine(rng, q, dim):
    add, mul = field(q)
    gens = [tuple(rng.randrange(q) for _ in range(dim)) for _ in range(rng.randint(1, dim - 1))]
    span = {tuple([0] * dim)}
    for g in gens:
        span = {tuple(add(s[i], mul(c, g[i])) for i in range(dim)) for s in span for c in range(q)}
    t0 = tuple(rng.randrange(q) for _ in range(dim))
    return {tuple(add(s[i], t0[i]) for i in range(dim)) for s in span}


