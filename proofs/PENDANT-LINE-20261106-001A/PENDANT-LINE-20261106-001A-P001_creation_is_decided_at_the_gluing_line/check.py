# ------------------------------------------------------------------------------------------------ 3. the exhaustive local verification
def local_task(args):
    fname, k, cols = args
    F = dict(SL.FARS)[fname]
    reps, rows = LL.far_classes(F)
    fr = LL.far_relation(rows, cols)
    if k not in REL:
        REL[k] = LL.near_relations(k)
    rel = REL[k]
    L = LL.Local(k, fr, len(cols))
    tot = collections.Counter()
    step = 1 << 20
    for a in range(0, len(rel), step):
        A = L.analyse(rel[a:a + step])
        ok = A["ok"]
        R2 = L.two_rounds(A)
        Rg, Ys = L.criterion(A)
        tot["relations"] += len(ok)
        tot["non-degenerate"] += int(ok.sum())
        tot["violations of the two-round rule"] += sum(L.closure_violations(A, R2).values())
        tot["faces where the two-round and switch rules differ"] += sum(int((ok & (R2[t] != Rg[t])).sum()) for t in R2)
        for drop in ("round 1", "pairs", "two far"):
            tot["violations with '%s' switched off" % drop] += sum(L.closure_violations(A, L.two_rounds(A, drop=(drop,))).values())
        for tri in A["knot"]:
            if A["cross"][tri]:
                kk = ok & A["knot"][tri]
                tot["crossing knots"] += int(kk.sum())
                tot["reached"] += int((kk & R2[tri]).sum())
    return args, tot


# ------------------------------------------------------------------------------------------------ 4, 5. agreement with the closure
def near_side(seed):
    r = random.Random(seed)
    if seed % 2:
        b = r.choice(sorted(GL.SP))
        H, s, n = GL.SP[b]
        return H, s, n, CL.solutions(H, s, n, skip=r.randrange(len(H)))
    n = r.randint(7, 10)
    m = r.randint(n - 2, n + 3)
    H = [tuple(r.sample(range(n), 3)) for _ in range(m)]
    s = [[r.randint(0, 1) for _ in range(3)] for _ in range(m)]
    return H, s, n, CL.solutions(H, s, n)


def predict(d, H, n, l):
    """the two-round rule on a whole splice"""
    rep, cset, base = d["rep"], d["cset"], d["base"]
    Y = sorted({rep[y] for y in H[l]})
    nearc = sorted({rep[q] for q in range(n)})
    far = sorted({rep[q] for q in d["far"]} - set(nearc))
    near = sorted(set(nearc) - set(Y))
    K = lambda *c: len(set(c)) == 3 and sum(1 << q for q in c) in cset  # noqa: E731
    Bk = lambda *c: len(set(c)) == 3 and sum(1 << q for q in c) in base  # noqa: E731
    r1 = {}
    reached = set()
    for c in far:
        for x in near:
            for y in Y:
                r1[(c, x, y)] = K(c, x, y) and any(Bk(c, y, z) and K(x, y, z) for z in Y if z != y)
                if r1[(c, x, y)]:
                    reached.add((1 << c) | (1 << x) | (1 << y))
        for x, w in itertools.combinations(near, 2):
            if K(c, x, w) and any(r1[(c, x, y)] and r1[(c, w, y)] for y in Y):
                reached.add((1 << c) | (1 << x) | (1 << w))
    for c, c2 in itertools.combinations(far, 2):
        for x in near:
            if K(c, c2, x) and any((Bk(c, c2, y) and (r1[(c, x, y)] or r1[(c2, x, y)])) or (r1[(c, x, y)] and r1[(c2, x, y)]) for y in Y):
                reached.add((1 << c) | (1 << c2) | (1 << x))
    return reached


def global_task(seed):
    H, s, n, AN = near_side(seed)
    out = collections.Counter()
    if len(AN) == 0:
        return out
    for l in range(len(H)):
        if len(set(H[l])) < 3 or not GL.six(AN, H[l]):
            continue
        for fname, F in SL.FARS:
            d = SL.closure_data(AN, H, s, n, l, F)
            pred = predict(d, H, n, l)
            crossing = d["cset"] - d["base"]
            Ycl = sorted({d["rep"][q] for q in range(d["n"]) if d["rep"][q] in {d["rep"][y] for y in H[l]}})
            restricted = SL.restricted_closure(d["cset"], d["base"], d["n"], Ycl)
            out["crossing classes"] += len(crossing)
            out["generated by the closure"] += len(crossing & d["gen"])
            out["the two-round rule agrees"] += sum(1 for T in crossing if (T in d["gen"]) == (T in pred))
            out["generated through the gluing line alone"] += len(crossing & restricted)
    return out


def engine_task(seed):
    """project a real splice onto the gluing line, three near classes and one or two far classes; compare the engine with the closure"""
    r = random.Random(10 ** 6 + seed)
    H, s, n, AN = near_side(seed)
    out = collections.Counter()
    if len(AN) == 0:
        return out
    lines = [l for l in range(len(H)) if len(set(H[l])) == 3 and GL.six(AN, H[l])]
    if not lines:
        return out
    l = r.choice(lines)
    fname, F = r.choice(SL.FARS)
    d = SL.closure_data(AN, H, s, n, l, F)
    rep, Y, sig = d["rep"], list(H[l]), s[l]
    lines_, signs_, far, AF = J.far_side(G, H, s, n, l, *F)
    reps_far, rows = LL.far_classes(F)
    nearc = sorted({rep[q] for q in range(n)} - {rep[y] for y in Y})
    farc = sorted({rep[q] for q in far} - {rep[q] for q in range(n)})
    if len(nearc) < 3 or not farc:
        return out
    for trial in range(4):
        xs = r.sample(nearc, 3)
        cs = r.sample(farc, r.choice([1, 2]) if len(farc) >= 2 else 1)
        fr = LL.far_relation(rows, [far.index(c) for c in cs])
        slots = 0
        for row in AN:
            yv = tuple(int(row[Y[j]]) ^ sig[j] for j in range(3))
            slots |= 1 << (LL.PY.index(yv) * 8 + sum(int(row[x]) << j for j, x in enumerate(xs)))
        L = LL.Local(3, fr, len(cs))
        A = L.analyse(np.array([slots], dtype=np.uint64))
        if not A["ok"][0]:
            out["degenerate projections"] += 1
            continue
        R = L.two_rounds(A)
        glob = [rep[y] for y in Y] + list(xs) + list(cs)
        for tri, kn in A["knot"].items():
            g = sum(1 << glob[p] for p in tri)
            out["triples"] += 1
            out["knot status agrees"] += bool(kn[0]) == (g in d["cset"])
            if A["cross"][tri] and kn[0]:
                out["crossing knots"] += 1
                out["reached status agrees"] += bool(R[tri][0]) == (g in d["gen"])
    return out


