#!/usr/bin/env python3
"""Census for KNOT-IMAGES-20261021-001A-E001 (contract.json).

Laws are multi-sorted: each relation has a signature of sorts, and systems only put a variable in positions of its own
sort. For every law in the roster:
- elimination on random systems and on fixed gadgets; the first failure is recorded with its system;
- candidate tops: on each range found (a set of values of one sort), the partition generated by the proper reflexive
  relations observed (two-variable projections between variables with that range, fibre-sharing relations of
  circuits). If it is the total relation the tops have collapsed, which a law that composes like cycles cannot do
  (CYCLE-TOPS-20261021-001B-P001, Lemma 1);
- for laws with neither: certified tops, hidden circuits, tie and knot top images, and a ternary polymorphism Mal'tsev
  modulo the tops on the knot ranges (one operation table per sort).
For Latin squares the group-isotope test is recorded: a quasigroup is isotopic to a group exactly when a principal loop
isotope is associative.

    python3 -B run.py
"""

